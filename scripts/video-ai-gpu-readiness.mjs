#!/usr/bin/env node
/**
 * Read-only GPU feasibility probe for an optional owner-hosted video model.
 * No installs, downloads, API submissions, provider keys or paid services.
 * Never describes the engine as operational without model, license and E2E.
 */
import {platform,arch,totalmem} from 'node:os';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

export function assessLocalVideoCompute({platformName,gpuVramMiB=0,ramGiB=0,nvidiaGpu=false}={}){
  if(platformName==='darwin')return Object.freeze({
    status:'requires_apple_silicon_model_compatibility_review',
    candidateOnly:true,comfyUiReady:false,canRenderNow:false,hardwareCostFree:false,
    reason:'Apple Metal/MPS memory and LTX checkpoint compatibility have not been verified.',
  });
  if(platformName!=='linux'&&platformName!=='win32')return Object.freeze({
    status:'unsupported_host',candidateOnly:false,comfyUiReady:false,canRenderNow:false,
  });
  if(!nvidiaGpu||!Number.isFinite(gpuVramMiB)||gpuVramMiB<=0)return Object.freeze({
    status:'no_verified_cuda_gpu',candidateOnly:false,comfyUiReady:false,canRenderNow:false,
  });
  if(gpuVramMiB<32768)return Object.freeze({
    status:'insufficient_vram_for_reference_32g_workflow',candidateOnly:false,
    comfyUiReady:false,canRenderNow:false,
    reason:'Smaller optimized checkpoints may exist but must pass their own benchmark.',
  });
  return Object.freeze({
    status:ramGiB>=32?'gpu_feasibility_candidate':'check_host_ram',
    candidateOnly:true,comfyUiReady:false,canRenderNow:false,
    reason:'Still requires licensed model weights, ComfyUI workflow, real generated clip and video QA.',
  });
}
function nvidiaGpu(){
  try{
    const raw=execFileSync('nvidia-smi',
      ['--query-gpu=memory.total,name','--format=csv,noheader,nounits'],
      {encoding:'utf8',timeout:3000,maxBuffer:4096});
    const first=raw.trim().split(/\r?\n/)[0]||'';
    const match=first.match(/^([0-9]+),\s*(.{2,100})$/);
    return match?{name:match[2],vramMiB:Number(match[1])}:null;
  }catch{return null;}
}
export function localVideoReadinessReport(){
  const gpu=nvidiaGpu();
  const host={platformName:platform(),arch:arch(),ramGiB:Math.round(totalmem()/2**30),
    gpuVramMiB:gpu?.vramMiB??0,nvidiaGpu:!!gpu};
  const verdict=assessLocalVideoCompute(host);
  // Hardware identity is local diagnostics only, not sent to telemetry.
  return {schema:'hh-video-gpu-check-v1',host,verdict,
    modelWeightsVerified:false,commercialLicenseVerified:false,
    comfyWorkflowVerified:false,generatedSampleMp4Verified:false,
    note:'Assessment only; no AI model installed or generated by this script.'};
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1]){
  process.stdout.write(JSON.stringify(localVideoReadinessReport(),null,2)+'\n');
}
