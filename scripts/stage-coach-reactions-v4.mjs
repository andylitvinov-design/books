// One-time local import into an authorized Git checkout. No network, generation,
// credentials, deployment or build jobs. Retain existing legacy files.
// Usage: node scripts/stage-coach-reactions-v4.mjs /path/to/downloads
//        [mira alternate:merlin ... | --all]
// Input: exact original files named as in the HeyGen V4 asset library.
import {readFile,writeFile,mkdir,copyFile,rename,stat} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import {resolve,join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {REACTION_V4_ANCHORS,reactionCameraGroup,reactionV4File,reactionV4Poster} from '../lib/coaching/coach-reaction-v4-registry.mjs'
import {REACTION_V4_RELEASED,REACTION_V5_CAMERA_GROUPS} from '../lib/coaching/coach-reaction-v4-release.mjs'

const source=process.argv[2]
if(!source)throw new Error('Pass the local source directory; no automatic download')
const requested=process.argv.slice(3)
const normalize=token=>{
  const [group,coach]=token.includes(':')?token.split(':'):['primary',token]
  if(!reactionCameraGroup(coach,group))throw new Error('Unknown reaction camera group: '+token)
  return group+':'+coach
}
const all=Object.keys(REACTION_V4_ANCHORS)
const groups=requested.includes('--all')?all.flatMap(c=>['primary:'+c,'alternate:'+c]):
  requested.length?requested.map(normalize):all.map(c=>'primary:'+c)
const selected=[...new Set(groups)]
const root=fileURLToPath(new URL('../',import.meta.url))
const dest=join(root,'public/images/holistic-house/my-coach-motion/reaction-v4')
const release=join(root,'lib/coaching/coach-reaction-v4-release.mjs')
function filesFor(token){
  const [group,coach]=normalize(token).split(':')
  const {anchor,entries}=reactionCameraGroup(coach,group)
  return [{name:reactionV4Poster(coach,group),sha:anchor.pngSha256},
    ...entries.map(([id,b])=>({name:reactionV4File(id),sha:b.sha256,size:b.size}))]
}
const required=selected.flatMap(filesFor)
async function verify(file,entry){
  const data=await readFile(file)
  if(entry.size&&data.length!==entry.size)throw new Error('Size mismatch: '+entry.name)
  if(createHash('sha256').update(data).digest('hex')!==entry.sha)throw new Error('SHA-256 mismatch: '+entry.name)
}
// Validate the entire request before copying or enabling ANY coach.
for(const e of required)await verify(resolve(source,e.name),e)
await mkdir(dest,{recursive:true})
for(const e of required){
  const target=join(dest,e.name)
  const exists=await stat(target).then(()=>true,()=>false)
  if(exists){await verify(target,e);continue}
  const tmp=target+'.staging'
  await copyFile(resolve(source,e.name),tmp)
  await verify(tmp,e)
  await rename(tmp,target)
}
const enabled=[...new Set([...REACTION_V4_RELEASED.map(normalize),...selected])].sort()
for(const token of enabled){
  for(const e of filesFor(token))await verify(join(dest,e.name),e)
}
for(const [coach,group] of Object.entries(REACTION_V5_CAMERA_GROUPS)){
  if(!enabled.includes(normalize(group+':'+coach)))throw new Error('Configured camera is not staged: '+coach)
}
const temp=release+'.staging'
await writeFile(temp,'// Verified first-party V4 source assets. Generated by the one-time import script.\nexport const REACTION_V4_RELEASED=Object.freeze('+JSON.stringify(enabled)+')\nexport const REACTION_V5_CAMERA_GROUPS=Object.freeze('+JSON.stringify(REACTION_V5_CAMERA_GROUPS)+')\n')
await rename(temp,release)
console.log('HH_COACH_REACTION_V4_STAGED',enabled.join(','),'Commit assets + allowlist together; run coaching release and real-device QA.')
