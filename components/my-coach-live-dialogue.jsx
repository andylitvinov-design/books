const reasons={
  feature_disabled:'disabled',server_not_configured:'config',rate_limited:'limit',
  privacy_model_unavailable:'protected',cost_unverified:'cost',
  response_unverified:'failed',model_unavailable:'retry',
}
const assistantText=(result)=>result.mode==='ai' && typeof result.message==='string'
  ? result.message : [result.reflection,result.hypothesis,result.question].filter(Boolean).join('\n\n')

export default function MyCoachLiveDialogue({locale='en',personaId='mira',settings={},onClose,onGuided}){
  const lang=copy[locale]?locale:'en',t=copy[lang]
  const persona=getCoachPersona(personaId)
  const [consent,setConsent]=useState(false)
  const [draft,setDraft]=useState('')
  const [turns,setTurns]=useState([])
  const [busy,setBusy]=useState(false)
  const [error,setError]=useState('')
  const [authRequired,setAuthRequired]=useState(false)
  const [readiness,setReadiness]=useState({status:'checking',reason:''})
  const [paused,setPaused]=useState(false)
  const [editablePlan,setEditablePlan]=useState('')
  const pending=useRef(null),end=useRef(null)
  useEffect(()=>()=>pending.current?.abort(),[])
  useEffect(()=>{
    // This probe sends only a synthetic OK to the free-only ZDR gateway.
    // The client's message and history remain untouched until consent + Send.
    const controller=new AbortController()
    fetch('/api/app/my-coach/probe',{
      method:'POST',credentials:'same-origin',cache:'no-store',signal:controller.signal,
      headers:{'Content-Type':'application/json'},body:'{}',
    }).then(async response=>{
      if(response.status===401){setAuthRequired(true);return null}
      const result=await response.json().catch(()=>null)
      if(!response.ok||result?.schema!=='HH_COACHING_BRAIN_PROBE_V1')throw Error('PROBE_FAILED')
      return result
    }).then(result=>{
      if(controller.signal.aborted)return
      setReadiness({status:result?.status==='verified'?'verified':'unavailable',reason:result?.reason||''})
    }).catch(()=>{
      if(!controller.signal.aborted)setReadiness({status:'unavailable',reason:'model_unavailable'})
    })
    return ()=>controller.abort()
  },[])
  useEffect(()=>{if(turns.length)end.current?.scrollIntoView({block:'nearest',behavior:'auto'})},[turns])
  const name=persona?localCoachText(persona.name,lang):t.coach
  const opening=persona?localCoachText(persona.opening,lang):t.goal

  async function send(event){
    event.preventDefault()
    return sendMessage(draft.trim())
  }
  async function sendMessage(raw){
    const message=String(raw||'').trim()
    if(!message||!consent||busy||paused||authRequired||readiness.status==='checking')return
    if(readiness.status!=='verified'){
      // Local-only authored fallback. NEVER send private text to an unverified model.
      // Same editorial persona prompts, same browser-only conversation history.
      const stages=['goal','reality','resources','options','action']
      const userCount=turns.filter(item=>item.role==='user').length
      const stage=stages[Math.min(userCount,stages.length-1)]
      const answer=String(coachStagePrompt(personaId,stage,lang,settings)||t.goal).slice(0,900)
      setTurns(previous=>{
        const updated=[...previous,{role:'user',content:message},{
          role:'assistant',content:answer,reflection:'',question:answer,
          mode:'offline',reason:'model_unavailable',stage,
        }]
        return updated.length>24?[updated[0],...updated.slice(-23)]:updated
      })
      setDraft('')
      return {reply:answer,mode:'offline'}
    }
    const controller=new AbortController()
    pending.current?.abort()
    pending.current=controller
    setBusy(true);setError('')
    try{
      const response=await fetch('/api/app/my-coach/turn',{
        method:'POST',credentials:'same-origin',cache:'no-store',signal:controller.signal,
        headers:{'Content-Type':'application/json'},
        body:JSON.stringify({
          personaId,settings,locale:lang,consent:true,message,
          turns:(turns.length>10?[turns[0],...turns.slice(-9)]:turns)
            .map(({role,content})=>({role,content})), // Keep the first client-stated goal in context.
        }),
      })
      if(response.status===401){setAuthRequired(true);return}
      const result=await response.json().catch(()=>null)
      if(!response.ok||!result?.mode||result.personaId!==personaId)throw Error('COACH_REPLY_UNAVAILABLE')
      if(controller.signal.aborted)return
      const answer=assistantText(result)
      if(!answer||answer.length>900)throw Error('COACH_REPLY_UNAVAILABLE')
      setTurns(previous=>{
        const updated=[...previous,{role:'user',content:message},{
          role:'assistant',content:answer,reflection:result.reflection,question:result.question,
          hypothesis:result.hypothesis||'',mode:result.mode,
          reason:result.offlineReason||'',stage:result.stage||'',
          suggestion:result.planSuggestion||'',evidence:result.evidenceQuote||'',
        }]
        return updated.length>24?[updated[0],...updated.slice(-23)]:updated
      })
      setDraft('')
      if(result.mode==='safety'||(result.mode==='boundary'&&result.boundary==='stop'))setPaused(true)
      if(result.mode==='ai'&&result.planSuggestion)setEditablePlan(result.planSuggestion)
      return {reply:answer,mode:result.mode}
    }catch{
      if(!controller.signal.aborted)setError(t.error)
      return null
    }finally{
      if(pending.current===controller){pending.current=null;setBusy(false)}
    }
  }
  return <section className={styles.root} lang={lang} data-my-coach-live-dialogue={personaId}>
    <header className={styles.header}>
      <span className={styles.badge}><Sparkles size={15} aria-hidden="true"/>{t.badge}</span>
      <h2>{t.title}</h2>
      <p>{t.disclosure}</p>
    </header>
    <div className={styles.messages} role="log" aria-live="polite" aria-relevant="additions text">
      <div className={styles.coachMessage}>
        <strong>{name}</strong>
        <p>{opening}</p>
      </div>
      {turns.map((turn,index)=><div key={index}
        className={turn.role==='user'?styles.userMessage:styles.coachMessage}>
        <strong>{turn.role==='user'?t.user:name}</strong>
        {turn.role==='assistant'&&turn.mode!=='ai'&&<small className={styles.meta}>
          {turn.mode==='safety'?t.crisis:t.offline}
        </small>}
        {turn.role==='assistant'?<>
          {turn.mode==='ai'?<p>{turn.content}</p>:<>
            {turn.reflection&&<p>{turn.reflection}</p>}
            {turn.hypothesis&&<p className={styles.hypothesis}>{turn.hypothesis}</p>}
            {turn.question&&<p className={styles.question}>{turn.question}</p>}
          </>}
          {turn.mode==='offline'&&<p className={styles.offline} role="status">
            {t.unavailable} {t[reasons[turn.reason]]||t.retry}
          </p>}
          {turn.suggestion&&<aside className={styles.suggestion}>
            <b>{t.plan}</b><p>{turn.suggestion}</p>
            {turn.evidence&&<small>{t.evidence}: «{turn.evidence}»</small>}
          </aside>}
        </>:<p>{turn.content}</p>}
      </div>)}
      <div ref={end}/>
    </div>
    {editablePlan&&<label className={styles.plan}>{t.plan}
      <textarea value={editablePlan} maxLength={300} rows={2}
        onChange={event=>setEditablePlan(event.target.value)}/>
    </label>}
    {!authRequired&&<p className={styles.readiness} role="status">
      {readiness.status==='checking'?t.verifying:readiness.status==='verified'?t.verified:
        t.unavailable+' '+(t[reasons[readiness.reason]]||t.retry)}
    </p>}
    {authRequired?<div className={styles.auth} role="status">
      <LockKeyhole size={20} aria-hidden="true"/>
      <span>{t.login}</span>
      <Link href={'/'+lang+'/my-coach'}>{t.loginLink}<ArrowRight size={16}/></Link>
    </div>:null}
    {!paused&&<form className={styles.composer} onSubmit={send}>
      <label htmlFor="hh-my-coach-live-input">{t.field}</label>
      <textarea id="hh-my-coach-live-input" value={draft} maxLength={1200} rows={2}
        placeholder={t.placeholder} disabled={busy||authRequired||readiness.status==='checking'}
        onChange={event=>{setDraft(event.target.value);setError('')}}/>
      <label className={styles.consent}>
        <input type="checkbox" checked={consent} disabled={busy||readiness.status==='checking'}
          onChange={event=>{setConsent(event.target.checked);if(!event.target.checked)pending.current?.abort()}}/>
        <span>{t.consent}</span>
      </label>
      <button className={styles.send} type="submit" disabled={!consent||busy||!draft.trim()||authRequired||readiness.status==='checking'}>
        {busy?t.sending:t.send}<Send size={18} aria-hidden="true"/>
      </button>
    </form>}
    <MyCoachSpeechLoop locale={lang}
      enabled={consent&&readiness.status!=='checking'&&!authRequired}
      canStart={!busy&&!paused} onTurn={sendMessage}
      onCancelTurn={()=>pending.current?.abort()}/>
    {error&&<p className={styles.error} role="alert">{error}</p>}
    <p className={styles.privacy}><ShieldCheck size={16} aria-hidden="true"/>{t.privacy}</p>
    <nav className={styles.actions}>
      <button type="button" onClick={onClose}><ArrowLeft size={16}/>{t.back}</button>
      {onGuided&&<button type="button" onClick={onGuided}>{t.guided}<Check size={16}/></button>}
    </nav>
  </section>
}
