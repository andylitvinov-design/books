-- Owner-only private store. This file name matches the applied Supabase migration version.
create table if not exists business_brain.commander_tasks (
  task_id uuid primary key,
  task_number bigint generated by default as identity unique,
  owner_id uuid not null references auth.users(id) on delete cascade,
  project_key text not null default 'agent-commander' references business_brain.projects(project_key),
  title text not null check (char_length(title) between 1 and 180),
  payload jsonb not null check (jsonb_typeof(payload)='object' and pg_column_size(payload)<=30000),
  state text not null default 'draft' check (state in ('draft','queued_review','blocked','completed','superseded')),
  revision integer not null default 1 check (revision>0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists commander_tasks_owner_updated_idx on business_brain.commander_tasks(owner_id,updated_at desc);
create index if not exists commander_tasks_project_updated_idx on business_brain.commander_tasks(project_key,updated_at desc);

create table if not exists business_brain.commander_chats (
  chat_id uuid primary key,
  chat_number bigint generated by default as identity unique,
  owner_id uuid not null references auth.users(id) on delete cascade,
  task_id uuid unique references business_brain.commander_tasks(task_id) on delete set null,
  title text not null check (char_length(title) between 1 and 180),
  payload jsonb not null check (jsonb_typeof(payload)='object' and pg_column_size(payload)<=30000),
  status text not null default 'planned' check (status in ('planned','assigned','working','review','blocked','completed','archived')),
  execution_state text not null default 'UNVERIFIED_ASSIGNMENT_ONLY'
    check (execution_state in ('UNVERIFIED_ASSIGNMENT_ONLY','AWAITING_EXECUTOR_NOT_DISPATCHED','DISPATCHED_UNVERIFIED','WORKING_UNVERIFIED','BLOCKED','SOURCE_VERIFIED','COMPLETED_UNVERIFIED')),
  revision integer not null default 1 check (revision>0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists commander_chats_owner_updated_idx on business_brain.commander_chats(owner_id,updated_at desc);
create index if not exists commander_chats_task_idx on business_brain.commander_chats(owner_id,task_id) where task_id is not null;

create table if not exists business_brain.commander_chat_events (
  event_id uuid primary key,
  chat_id uuid not null references business_brain.commander_chats(chat_id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('owner','assistant_unverified','note','github_report')),
  payload jsonb not null check (jsonb_typeof(payload)='object' and pg_column_size(payload)<=10000),
  source_verified boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists commander_chat_events_owner_chat_time_idx on business_brain.commander_chat_events(owner_id,chat_id,created_at);

alter table business_brain.commander_tasks enable row level security;
alter table business_brain.commander_tasks force row level security;
alter table business_brain.commander_chats enable row level security;
alter table business_brain.commander_chats force row level security;
alter table business_brain.commander_chat_events enable row level security;
alter table business_brain.commander_chat_events force row level security;
revoke all on business_brain.commander_tasks from public,anon,authenticated,service_role;
revoke all on business_brain.commander_chats from public,anon,authenticated,service_role;
revoke all on business_brain.commander_chat_events from public,anon,authenticated,service_role;

comment on table business_brain.commander_tasks is 'Private owner-only Agent Commander tasks; access only via the owner-verified Edge Function.';
comment on table business_brain.commander_chats is 'Private owner-only Agent Commander chat headers; direct Data API access is revoked.';
comment on table business_brain.commander_chat_events is 'Private owner-only Agent Commander events; assistant content is unverified unless independently proven.';
