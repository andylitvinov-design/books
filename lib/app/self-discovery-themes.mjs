export const discoveryTag=id=>'self-discovery:'+id
export function themeMatches(entry,id){
 if(id==='all')return true
 const tags=Array.isArray(entry?.topics)?entry.topics:[]
 if(id==='other')return !DISCOVERY_THEMES.some(t=>t.tags.some(tag=>tags.includes(tag)))
 return Boolean(DISCOVERY_THEMES.find(t=>t.id===id)?.tags.some(tag=>tags.includes(tag)))
}
export const freeDiscoveryEntries=entries=>entries.filter(e=>e.selectable===true&&e.free===true)
export function themeProgress(entries,verified,id){
 const keys=new Set(entries.filter(e=>themeMatches(e,id)).map(e=>e.key))
 return {total:keys.size,done:new Set(verified.filter(r=>keys.has(r.definitionKey)).map(r=>r.definitionKey)).size}
}
export function themeResults(results,entries,id){
 if(id==='all')return results
 const index=new Map(entries.map(e=>[e.key,e]))
 return results.filter(r=>themeMatches(index.get(r.definitionKey),id))
}

// Navigation carries only fixed editorial theme and locale, never an account ID or arbitrary destination.
export const discoveryTheme=id=>DISCOVERY_THEMES.some(row=>row.id===id)?id:'love'
export const discoveryView=value=>['tests','results'].includes(value)?value:null
export function discoverySourceQuery(theme,locale){
 return new URLSearchParams({from:'self-discovery',discoveryTheme:discoveryTheme(theme),discoveryLocale:['en','ru','es'].includes(locale)?locale:'en'}).toString()
}
export function discoveryNavigation(query,accountLocale){
 if(!query||query.getAll('from').length!==1||query.get('from')!=='self-discovery')return null
 const locale=['en','ru','es'].includes(accountLocale)?accountLocale:'en'
 const requested=query.getAll('discoveryLocale').length===1?query.get('discoveryLocale'):null
 const displayLocale=requested===locale||(locale==='en'&&requested==='es')?requested:locale
 const theme=discoveryTheme(query.getAll('discoveryTheme').length===1?query.get('discoveryTheme'):null)
 return {source:discoverySourceQuery(theme,displayLocale),href:'/'+displayLocale+'/app/daybook/self-discovery?theme='+encodeURIComponent(theme)+'&view=results'}
}
