export function businessTag(week,step){
 if(!Number.isInteger(week)||week<1||week>4||!Number.isInteger(step)||step<1||step>3)throw Error('BUSINESS_TASK_INVALID');
 return 'hh-business-v1-w'+week+'-s'+step;
}
export function savedBusinessTask(entries,week,step){
 const tag=businessTag(week,step);
 return (Array.isArray(entries)?entries:[]).filter(e=>e?.kind==='note'&&e.goalId===null&&Number.isInteger(e.revision)&&e.revision>0&&Array.isArray(e.tags)&&e.tags.length===1&&e.tags[0]===tag&&typeof e.text==='string'&&e.text.trim()).sort((a,b)=>String(b.updatedAt||'').localeCompare(String(a.updatedAt||''))||String(a.id).localeCompare(String(b.id)))[0]||null;
}
export function businessProgress(entries){
 let completed=0,next=null;const weeks=[];
 for(let week=1;week<=4;week++){
  let count=0;for(let step=1;step<=3;step++){if(savedBusinessTask(entries,week,step)){count++;completed++}else if(!next)next={week,step}}
  weeks.push(count)
 }
 return {completed,total:12,percent:Math.round(completed*100/12),weeks,next}
}
