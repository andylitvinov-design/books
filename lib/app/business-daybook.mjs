export const BUSINESS_SESSION_COUNT=8
export const BUSINESS_PRACTICE_COUNT=3
export const BUSINESS_REPORT_ROOT='/reports/business-program'
export function businessSessionScreenshot(locale,session){
 if(!Number.isInteger(session)||session<1||session>BUSINESS_SESSION_COUNT)throw Error('BUSINESS_SESSION_INVALID')
 return BUSINESS_REPORT_ROOT+'/'+(locale==='ru'?'ru':'en')+'-'+session+'.webp'
}
export function businessTag(week,step){
 if(!Number.isInteger(week)||week<1||week>BUSINESS_SESSION_COUNT||!Number.isInteger(step)||step<1||step>BUSINESS_PRACTICE_COUNT)throw Error('BUSINESS_TASK_INVALID')
 return 'hh-business-v2-w'+week+'-s'+step
}
function savedByTag(entries,tag){
 return (Array.isArray(entries)?entries:[]).filter(e=>e?.kind==='note'&&e.goalId===null&&Number.isInteger(e.revision)&&e.revision>0&&Array.isArray(e.tags)&&e.tags.length===1&&e.tags[0]===tag&&typeof e.text==='string'&&e.text.trim()).sort((a,b)=>String(b.updatedAt||'').localeCompare(String(a.updatedAt||''))||String(a.id).localeCompare(String(b.id)))[0]||null
}
export function savedBusinessTask(entries,week,step){return savedByTag(entries,businessTag(week,step))}
export function legacyBusinessTasks(entries,locale='en'){
 const syllabus=LEGACY_BUSINESS_SYLLABUS[locale]||LEGACY_BUSINESS_SYLLABUS.en
 return syllabus.flatMap(([title,,tasks],i)=>tasks.flatMap(([task],j)=>{
  const tag='hh-business-v1-w'+(i+1)+'-s'+(j+1),entry=savedByTag(entries,tag)
  return entry?[{tag,title,task,text:entry.text}]:[]
 }))
}
export function businessProgress(entries){
 let completed=0,next=null;const weeks=[]
 for(let week=1;week<=BUSINESS_SESSION_COUNT;week++){
  let count=0;for(let step=1;step<=BUSINESS_PRACTICE_COUNT;step++){if(savedBusinessTask(entries,week,step)){count++;completed++}else if(!next)next={week,step}}
  weeks.push(count)
 }
 const total=BUSINESS_SESSION_COUNT*BUSINESS_PRACTICE_COUNT
 return {completed,total,percent:Math.round(completed*100/total),weeks,next}
}
