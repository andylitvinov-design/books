import 'server-only'
import { randomUUID } from 'node:crypto'
import { transaction } from './database.js'
import { seal, openSealed } from './crypto.js'
import { AppError, requireUUID } from '../assessments/contracts.js'
import { normalizeLabReport } from '../labs/analysis.mjs'

// Original source files, pasted lab text, names, DOBs and addresses are never persisted.
// The entire confirmed structured report (including report date) is AES-256-GCM sealed.
const sealContext = (actor, id) => ({ accountId: actor.id, recordId: id, field: 'health.laboratory' })
const MAX_REPORTS = 24

async function assertAccount(db, actor, lock = false) {
  const result = await db.query(
    "select id from app.accounts where id=$1 and status='active' and onboarding_state='active'" + (lock ? ' for update' : ''),
    [actor.id],
  )
  if (!result.rows.length) throw new AppError('ACCOUNT_REQUIRED', 401)
}
function view(row, config, actor) {
  const value = openSealed(row.payload_ciphertext, sealContext(actor, row.id), config)
  // Read-time fail closed if data is damaged or was generated by an incompatible version.
  if (!normalizeLabReport({ ...value, confirmed: true })) throw new AppError('PRIVATE_DATA_UNAVAILABLE', 503)
  return { id: row.id, ...value, savedAt: row.created_at instanceof Date ? row.created_at.toISOString() : row.created_at }
}
export async function listLabReports(config, actor) {
  return transaction(config, actor, async db => {
    await assertAccount(db, actor)
    const rows = (await db.query(
      'select id,payload_ciphertext,created_at from app_private.lab_reports where account_id=$1 order by created_at desc,id desc limit 24',
      [actor.id],
    )).rows
    return { reports: rows.map(row => view(row, config, actor)) }
  })
}
export async function saveLabReport(config, actor, input) {
  const normalized = normalizeLabReport(input)
  if (!normalized || Object.keys(input).some(key => !['version','labName','measuredOn','sourceFormat','markers','confirmed'].includes(key)))
    throw new AppError('INVALID_LAB_REPORT', 400)
  if (JSON.stringify(normalized).length > 24000) throw new AppError('PAYLOAD_TOO_LARGE', 413)
  return transaction(config, actor, async db => {
    await assertAccount(db, actor, true)
    const count = (await db.query('select count(*)::integer as n from app_private.lab_reports where account_id=$1', [actor.id])).rows[0]?.n || 0
    if (count >= MAX_REPORTS) throw new AppError('LAB_REPORT_LIMIT', 409)
    const id = randomUUID()
    const ciphertext = seal(normalized, sealContext(actor, id), config)
    const row = (await db.query(
      'insert into app_private.lab_reports(id,account_id,payload_ciphertext) values($1,$2,$3) returning id,payload_ciphertext,created_at',
      [id, actor.id, ciphertext],
    )).rows[0]
    return { report: view(row, config, actor), saved: true }
  })
}
export async function deleteLabReport(config, actor, id) {
  requireUUID(id)
  return transaction(config, actor, async db => {
    await assertAccount(db, actor)
    const row = (await db.query(
      'delete from app_private.lab_reports where id=$1 and account_id=$2 returning id',
      [id, actor.id],
    )).rows[0]
    if (!row) throw new AppError('NOT_FOUND', 404)
    return { deleted: true, id: row.id }
  })
}
