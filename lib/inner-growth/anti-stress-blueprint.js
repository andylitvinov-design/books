export function antiStressBlueprint(locale='en'){
 const lang=['ru','en','es'].includes(locale)?locale:'en'
 const skills=antiStressPublicSkillsV5(lang).map(base=>({
   id:base.id,days:base.days,title:base.title,
   description:base.description||base.result,
   outcome:base.result,
   measureIds:base.measureIds,
 }))
 const days=antiStressPublicPlanV7(lang).map(day=>({
   ...day,methodNames:lang==='ru'?['Освоение навыка','Главная практика','Применение в жизни']:
     lang==='es'?['Introducción','Práctica principal','Uso cotidiano']:
     ['Skill introduction','Main practice','Everyday use'],
   methodStatus:'implemented',expectedResponse:day.result,
   skillName:skills[(day.day-1)%7].title,
 }))
 return Object.freeze({locale:lang,skills,days,
   outcomes:expected[lang],
   metrics:OPORA_METRICS.map(item=>({...item,label:item.label[lang],why:item.why[lang]})),
   tests:OPORA_TESTS.map(item=>({...item,title:item.title[lang],note:item.note[lang]})),
   approaches:OPORA_APPROACHES.map(item=>({...item,title:item.title[lang],explanation:item.explanation[lang]})),
   schedule:schedule[lang]})
}
