const LANGUAGES=Object.freeze(['en','ru','es'])
export function oporaAs59Skills(locale='en'){
  const lang=LANGUAGES.includes(locale)?locale:'en'
  return SKILLS.map((skill,index)=>Object.freeze({
    id:skill.id,title:skill.name[lang],description:skill.purpose[lang],
    days:Object.freeze([index+1,index+8]),outcome:skill.deep.result[lang],
  }))
}
export function oporaAs59Day(day,locale='en'){
  if(!Number.isInteger(day)||day<1||day>14)return null
  const lang=LANGUAGES.includes(locale)?locale:'en'
  const index=(day-1)%7,skill=SKILLS[index]
  const deep=day>7,activity=deep?skill.deep:skill.basic
  return Object.freeze({
    day,skillId:skill.id,skillNumber:index+1,skill:skill.name[lang],
    stage:deep?'deepen':'discover',title:activity.title[lang],
    purposeTitle:skill.name[lang],purpose:skill.purpose[lang],
    practice:activity.practice[lang],transfer:activity.transfer[lang],
    result:activity.result[lang],scenario:activity.scenario[lang],
    alternative:activity.alternative[lang],
    quote:(deep?skill.quoteDeep:skill.quote)[lang],
  })
}
export function oporaAs59Valid(){
  const unique=new Set()
  return SKILLS.length===7&&SKILLS.every((skill,index)=>
    skill.id==='S'+(index+1)&&LANGUAGES.every(lang=>
      skill.name[lang].length>=8&&skill.purpose[lang].length>=65&&skill.purpose[lang].length<=225
    ))&&Array.from({length:14},(_,i)=>i+1).every(day=>
    LANGUAGES.every(lang=>{
      const entry=oporaAs59Day(day,lang)
      if(!entry||entry.skillId!=='S'+((day-1)%7+1))return false
      for(const key of ['title','practice','transfer','result','scenario','alternative','quote']){
        const text=entry[key]
        if(typeof text!=='string'||text.trim().length<12||text.length>190||text.includes('\\n'))return false
      }
      if(entry.practice===entry.transfer)return false
      unique.add(lang+':'+entry.practice)
      return true
    }))&&unique.size===42
}
