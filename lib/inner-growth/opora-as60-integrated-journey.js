export function oporaAs60Journey(day,locale='en'){
 if(!Number.isInteger(day)||day<1||day>14)return null
 const lang=LANGS.includes(locale)?locale:'en',item=DAYS[day-1],head=LABELS[lang]
 return Object.freeze({
  day,
  body:Object.freeze({...head.body,text:item.body[lang]}),
  emotion:Object.freeze({...head.emotion,text:item.emotion[lang]}),
  mental:Object.freeze({...head.mental,text:item.observe[lang],plan:item.plan[lang]}),
  imagery:Object.freeze({...head.imagery,text:item.image[lang]}),
  ritual:Object.freeze({...head.ritual,text:item.ritual[lang]}),
 })
}
export function oporaAs60JourneyValid(){
 const all=new Set()
 if(DAYS.length!==14)return false
 for(let day=1;day<=14;day++)for(const locale of LANGS){
  const item=oporaAs60Journey(day,locale)
  if(!item||Object.keys(item).length!==6)return false
  for(const key of OPORA_EXPERIENCE_CHANNELS){
   const obj=item[key]
   if(!obj||!obj.title||!obj.hint||!obj.text||obj.text.length<35||obj.text.length>220)return false
   all.add(locale+':'+key+':'+obj.text)
  }
  if(item.mental.plan.length<35||item.mental.plan.length>205)return false
 }
 return all.size===14*5*LANGS.length
}
