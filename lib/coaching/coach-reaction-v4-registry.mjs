export function releasedCoachPresentationLoop(coach,released=[],group='primary'){
  const media=releasedReactionMedia(coach,released,group)
  if(!media)return null
  const id=COACH_PRESENTATION_LOOPS[group]?.[coach]
  const block=media.blocks.find(b=>b.id===id&&b.anchorHash===media.anchorHash)
  if(!block)return null
  return {...block,group,poster:media.poster}
}
