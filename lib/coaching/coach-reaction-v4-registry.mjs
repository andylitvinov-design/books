export function reactionCameraGroup(coach,group='primary'){
  if(group!=='primary'&&group!=='alternate')return null
  const anchors=group==='alternate'?REACTION_V5_ALTERNATE_ANCHORS:REACTION_V4_ANCHORS
  if(!Object.hasOwn(anchors,coach))return null
  const source=group==='alternate'?REACTION_V5_ALTERNATE_BLOCKS:REACTION_V4_BLOCKS
  const anchor=anchors[coach]
  const entries=Object.entries(source).filter(([,b])=>b.coach===coach)
  if(!entries.length||entries.some(([,b])=>b.anchorHash!==anchor.hash||!Number.isInteger(b.frames)||b.frames>MAX_COACH_REACTION_FRAMES||!coachReactionDurationAllowed(b.frames/24)))return null
  return {group,coach,anchor,entries}
}
