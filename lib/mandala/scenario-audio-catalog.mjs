const ALLOWED_ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export function isScenarioAudioId(value) {
  if(typeof value!=="string"||!value.startsWith("score-"))return false;
  const match=/^score-(.+)-([1-4])$/.exec(value);
  return !!match && ALLOWED_ID.test(match[1]) && REGISTRY.has(match[1]);
}
export function isClassicalAudioId(value) {
  return CLASSICAL_THEMES.some(x=>x.id===value);
}
