export const PHONE_COUNTRIES = Object.freeze(rows.map(([iso,dial,flag,en,ru,es])=>
  Object.freeze({iso,dial,flag,names:Object.freeze({en,ru,es})})));
export const E164_PHONE = /^\+[1-9]\d{7,14}$/;
export function phoneCountryFromValue(value) {
  if(typeof value!=="string"||!value.startsWith("+"))return "CA";
  const matching=PHONE_COUNTRIES.filter(c=>c.dial&&value.startsWith(c.dial))
    .sort((a,b)=>b.dial.length-a.dial.length);
  return matching[0]?.iso||"OTHER";
}
export function phoneNationalPart(value,dial) {
  if(typeof value!=="string"||!value.trim())return "";
  const clean=value.trim().replace(/[^\d+]/g,"");
  return dial&&clean.startsWith(dial)?clean.slice(dial.length):clean;
}
export function composeCountryPhone(dial,input) {
  if(typeof input!=="string"||!input.trim())return "";
  const clean=input.trim(),digits=clean.replace(/\D/g,"");
  if(!digits)return "";
  if(clean.startsWith("+"))return "+"+digits;
  if(!dial)return digits; // "Other" requires an explicitly typed +code.
  const prefix=dial.slice(1);
  // Do not duplicate the dial code if a complete number was pasted.
  if(digits.startsWith(prefix) &&
     (dial==="+1"?digits.length===11:digits.length>prefix.length+8))
    return "+"+digits;
  return dial+digits;
}
