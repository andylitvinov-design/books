export function telegramServiceOption(id,locale='en'){
 if(!['ru','en','es'].includes(locale)||typeof id!=='string'||
   !/^[a-z]+(?:_[a-z0-9-]+)+$/.test(id)||!Object.hasOwn(TELEGRAM_SERVICE_OPTIONS,id))return null;
 const row=TELEGRAM_SERVICE_OPTIONS[id];
 return {id,locale,title:row.titles[locale],...row};
}
export function telegramServiceOptionStart(text){
 const m=/^\/start(?:@[A-Za-z0-9_]{5,32})?\s+hhitem_([a-z]+(?:_[a-z0-9-]+)+)_(ru|en|es)$/i.exec(String(text||'').trim());
 const offer=m&&telegramServiceOption(m[1].toLowerCase(),m[2].toLowerCase());
 if(offer&&offer.channels&&!offer.channels.includes('telegram_bot'))return null;
 return offer?{service:offer.service,locale:offer.locale,offerId:offer.id}:null;
}
/** A native HTTPS Telegram app link avoids an intermediary 307 on iOS/in-app browsers.
 * The public allowlist is authoritative: arbitrary client-supplied offer ids never
 * produce a Telegram URL. Telegram still requires an explicit Start and consent.
 */
export function telegramServiceOptionDirectBotUrl(id,locale){
 const option=telegramServiceOption(id,locale);
 return option&&(!option.channels||option.channels.includes('telegram_bot'))
  ?'https://t.me/holistichouse_bot?start=hhitem_'+option.id+'_'+option.locale:null;
}
export function telegramServiceOptionRequestUrl(id,locale){
 const option=telegramServiceOption(id,locale);
 return option&&(!option.channels||option.channels.includes('telegram_bot'))
  ?'/api/public/telegram-option-entry?offer='+id+'&locale='+locale:null;
}
