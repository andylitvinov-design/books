import test from 'node:test'
import {assertStudioDeliveryOrder} from './helpers/report-editor-contracts.mjs'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {emptySessionDraft,normalizeDraft,clientPayload} from '../lib/clients/delivery-model.js'

const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const DOC='a18b8d2a-e6e3-4b11-baad-f9401a2c16a3'

test('saved consultation report can be delivered without filling a second plan form',()=>{
  const editor=source('components/admin-session-studio.jsx')
  const report=source('components/prescription-document.jsx')
  const model=source('lib/clients/delivery-model.js')
  const {first,personal,optional,materials,recorder,publication}=assertStudioDeliveryOrder(editor)
  assert.ok(editor.indexOf('Привязанный отчёт (настоящий PDF)')<personal)
  assert.ok(editor.indexOf('Главный фокус встречи')>optional)
  assert.ok(editor.indexOf('Главный фокус встречи')<materials)
  assert.ok(editor.indexOf('Материалы из библиотеки')>materials)
  assert.ok(editor.indexOf('<SessionMaterialPicker locale={locale}')>materials)
  assert.ok(editor.indexOf('<SessionMaterialPicker locale={locale}')<publication)
  assert.match(editor,/id="session-attached-report"/)
  assert.match(editor,/href="#session-publication"/)
  assert.match(editor,/id="session-publication"/)
  assert.match(editor,/Готовый отчёт клиента/)
  assert.match(editor,/Заполнять их повторно для публикации не нужно/)
  assert.match(editor,/Сохранить черновик/)
  assert.match(editor,/onClick=\{\(\)=>act\('publish'\)\}/)
  assert.match(editor,/publication=\{expectedRevision:session\.draftRevision/);assert.match(editor,/publication\.expectedRevision=saved\.draftRevision/);assert.match(editor,/expectedReportFingerprint:source\.reportFingerprint/)
  assert.match(editor,/href=\{'\/admin\/documents\/'/)
  assert.match(report,/canonical-report-analysis/)
  assert.match(report,/DocumentSignature/)
  assert.match(model,/clientPayload = draft/)
  const draft=normalizeDraft(emptySessionDraft({title:'Saved report',reportDocumentId:DOC}))
  assert.equal(draft.reportDocumentId,DOC)
  assert.equal(draft.plan.focus,'')
  assert.equal(draft.plan.nextStep,'')
  assert.deepEqual(draft.plan.takeaways,[])
  assert.deepEqual(draft.plan.practices,[])
  assert.equal(clientPayload(draft).reportDocumentId,DOC)
})

test('duplicate consultation questions are closed by default and require deliberate expansion',()=>{
  const editor=source('components/admin-session-studio.jsx')
  const css=source('components/client-session.module.css')
  const details=(editor.match(/<details className=\{styles\.optionalTextEditor\}>/g)||[])
  assert.equal(details.length,2)
  assert.doesNotMatch(editor,/<details className=\{styles\.optionalTextEditor\}[^>]*\bopen/)
  assert.match(editor,/Boolean\(draft\.summary\?\.trim\(\)\)/)
  assert.match(editor,/const hasExtraText=Boolean\(/)
  assert.match(editor,/hasExtraText&&<span className=\{styles\.optionalFilled\}>/)
  assert.match(editor,/Дополнительные заметки и упражнения \(необязательно\)/)
  assert.match(editor,/Для обычной публикации оставьте их пустыми/)
  assert.match(css,/\.adminStudio \.optionalTextEditor\{/)
  assert.match(css,/\.adminStudio \.optionalTextEditor > summary:focus-visible|\.adminStudio :is\(\.optionalTextEditor > summary,/)
  assert.match(css,/@media\(max-width:580px\)/)
})

