import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')

test('Profile starts with truthful, compact authorized-record summary before navigation', () => {
  const profile = read('components/app/profile-domains.jsx')
  const hero = profile.indexOf('<header className="hh-domain-hero">')
  const glance = profile.indexOf('<dl className="hh-domain-glance"')
  const tabs = profile.indexOf('<div className="hh-domain-tabs"')
  const panel = profile.indexOf('<div role="tabpanel"')
  const support = profile.indexOf('<details className="hh-domain-support">')
  const discover = profile.indexOf('<details className="hh-domain-discover">')
  assert.ok(hero >= 0 && glance > hero && tabs > glance && panel > tabs)
  assert.ok(support > panel && discover > support, 'extra offers must be below primary profile content')
  assert.doesNotMatch(profile.slice(hero, tabs), /<FreeInsightsPaths|<ProfileServiceOffer/)
  assert.match(profile, /const reportCount = external \? reports\.filter\(report => report\.available !== false\)\.length/)
  assert.match(profile, /savedReports\.filter\(report => report\.available !== false\)\.length/)
  assert.match(profile, /const remedyCount = external \? homeopathyUpdates\.length/)
  assert.match(profile, /recentResults\.length/)
  assert.match(profile, /readableDate\(latestDate, locale\) \|\| '—'/)
  assert.doesNotMatch(profile, /Math\.random\(|mockProfileScore|syntheticScores/)
})

test('Profile retains all four keyboard-accessible tabs and hides optional offers by default', () => {
  const profile = read('components/app/profile-domains.jsx')
  const css = read('components/app/profile-domains.css')
  assert.match(profile, /const DOMAINS = PROFILE_AREAS/)
  assert.match(profile, /role="tablist"/)
  assert.match(profile, /role="tab"/)
  assert.match(profile, /aria-selected=\{active === key\}/)
  assert.match(profile, /role="tabpanel"/)
  assert.match(profile, /aria-labelledby=\{'hh-domain-tab-' \+ active\}/)
  assert.match(profile, /event\.key === 'ArrowRight'/)
  assert.match(profile, /event\.key === 'ArrowLeft'/)
  assert.match(profile, /event\.key === 'Home'/)
  assert.match(profile, /event\.key === 'End'/)
  assert.match(profile, /<details className="hh-domain-support">/)
  assert.match(profile, /<details className="hh-domain-discover">/)
  assert.match(profile, /<ProfileServiceOffer area=\{active\} locale=\{locale\} \/>/)
  assert.match(profile, /<FreeInsightsPaths locale=\{locale\} variant="cabinet"/)
  assert.match(css, /--domain-accent:#762f49/)
  assert.match(css, /\.hh-domain-tabs \{[\s\S]*?overflow-x:auto/)
  assert.match(css, /@media\(max-width:420px\)/)
  assert.match(css, /prefers-reduced-motion:reduce/)
})

