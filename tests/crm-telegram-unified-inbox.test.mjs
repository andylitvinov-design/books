import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {canReply,channelTransportReady,MESSENGER_CHANNELS} from '../lib/crm/messenger-policy.js'
const source=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
const capture=source('lib/crm/telegram-lead-capture.js')
const hook=source('lib/crm/messenger-webhook.js')
const handler=source('app/api/app/crm/messenger/webhook/[provider]/route.js')
const store=source('lib/crm/messenger-store.js')
const api=source('app/api/app/crm/messenger/route.js')
const provider=source('lib/crm/messenger-provider.js')
const simple=source('components/app/messages-simple-inbox.jsx')
const ui=source('components/app/crm-messenger.jsx')
const now=Date.UTC(2026,10,18,12,0,0)
test('Business is an internal display channel and replies close after 23h',()=>{
 assert.equal(MESSENGER_CHANNELS.includes('telegram_business'),false)
 const last=new Date(now-60000).toISOString()
 assert.equal(canReply({channel:'telegram_business',lastInboundAt:last,suppressed:false,enabled:true,now}).ok,true)
 assert.equal(canReply({channel:'telegram_business',lastInboundAt:new Date(now-24*3600000).toISOString(),suppressed:false,enabled:true,now}).reason,'REPLY_WINDOW_CLOSED')
 assert.equal(channelTransportReady('telegram_business',{HH_CRM_TG_CHAT_AUTOMATION_ENABLED:'false'}),false)
 assert.match(provider,/if\(channel==='telegram_business'\)throw new AppError/)
})
test('verified Telegram Business records an encrypted, distinct CRM conversation',()=>{
 assert.match(capture,/assertHolisticBusinessConnection/)
 assert.match(capture,/crm_msg_resolve/)
 assert.match(capture,/provider:'telegram_business'/)
 assert.match(capture,/telegramBusinessVerified:true/)
 assert.match(capture,/tg-business:.*event\.updateId/)
 assert.match(hook,/businessPeer=provider==='telegram'&&event.telegramBusinessVerified===true/)
 assert.match(hook,/origin:'telegram_business'/)
 assert.match(hook,/telegramBusinessConnectionId/)
 assert.match(capture,/crm_tg_suppress_existing/)
 assert.doesNotMatch(capture,/insert into app\.crm_contacts/)
})
test('owner CRM and mobile Messages use the correct channel, owner scope, provider',()=>{
 assert.match(store,/effectiveChannel/)
 assert.match(store,/telegramBusinessReplyTarget/)
 assert.match(store,/text.length>600/)
 assert.match(store,/\['telegram','telegram_business'\]\.includes\(selected\.channel\)/)
 assert.match(store,/person\?\.origin!=='telegram_business'/)
 assert.match(api,/dispatch\.channel==='telegram_business'/)
 assert.match(api,/sendHolisticBusinessRequestReply/)
 assert.match(simple,/telegram_business:'Telegram · @holistichouse'/)
 assert.match(ui,/telegram_business:'Telegram · @holistichouse'/)
 assert.match(handler,/suppressTelegramBusinessLead\(body,config\)/)
 assert.match(handler,/stop\.blocked\|\|stop\.justStopped/)
})
test('client bot conversations enter CRM after /agree, never from unconsented start',()=>{
 assert.match(capture,/if\(!permitted\)return false/)
 assert.match(capture,/ai_consent_at/)
 assert.match(capture,/session\.stage!=='stopped'/)
 assert.match(handler,/captureTelegramBotConsentedMessage\(event,config\)/)
 assert.doesNotMatch(capture,/marketing_opt_in_at|crm_consent_ledger/)
})
test('owner inbox active refresh avoids global polling and invasive overlays',()=>{
 assert.match(ui,/window\.setTimeout\(/)
 assert.match(ui,/document\.visibilityState==='visible'/)
 assert.match(ui,/60000/)
 assert.doesNotMatch(simple,/window\.Notification|showModal|createPortal/)
})

test('confirmed Business order reuses original CRM peer rather than duplicating a lead',()=>{
 const service=source('lib/crm/telegram-business-service.js')
 assert.match(service,/provider:'telegram_business'/)
 assert.match(service,/scope:'crm-msg-contact'/)
 assert.match(service,/userId:intent.chatId/)
 assert.match(service,/origin:'telegram_business'/)
 assert.doesNotMatch(service,/scope:'crm-tg-business-peer'/)
})

test('transient history persistence still replies and retries the signed update',()=>{
 assert.match(handler,/HH_TG_CONSENTED_HISTORY_UNAVAILABLE/)
 assert.match(handler,/botLeadCapturePendingRetry=true/)
 assert.match(handler,/if\(businessLead\?\.unavailable\)/)
 assert.match(handler,/if\(stop\.blocked\|\|stop\.justStopped\)/)
 assert.match(handler,/TELEGRAM_CRM_STOP_UNCONFIRMED/)
})
