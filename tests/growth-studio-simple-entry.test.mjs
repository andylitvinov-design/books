test('three simple draft fields shown first; everything else under native advanced disclosure',()=>{
  const studio=read('components/growth-studio.jsx')
  const start=studio.indexOf('<div className={styles.quickComposerFields}>')
  const close=studio.indexOf('</div>',start)
  const extra=studio.indexOf('<details className={styles.composerOptions}>',close)
  const advancedEnd=studio.indexOf('</details>',extra)
  const save=studio.indexOf('<div className={styles.editorActions}>',advancedEnd)
  assert.ok(start>0 && close>start && extra>close && advancedEnd>extra && save>advancedEnd)
  const basic=studio.slice(start,close)
  for(const item of ['t.channel','t.title','t.caption'])assert.ok(basic.includes(item),item)
  for(const item of ['t.brand','t.language','t.campaign','t.media','t.source','t.schedule'])
    assert.ok(studio.slice(extra,advancedEnd).includes(item),item)
  assert.doesNotMatch(basic,/t\.campaign|t\.schedule|t\.mediaAlt|t\.brand/)
  assert.match(studio,/initialLocale==='ru'\?'ru':'en'/)
  assert.match(studio,/locale:initialLocale==='ru'\?'ru':'en'/)
})

