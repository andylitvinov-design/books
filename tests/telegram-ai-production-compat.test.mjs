test('client webhook is the ONLY account-bound AI-video ingress without changing bot registration',()=>{
 assert.match(webhook,/verifyClientTelegramSecret\(request\.headers\.get\('x-telegram-bot-api-secret-token'\)\)/)
 assert.match(webhook,/parseTelegramVideoClientIngress\(update,telegramClientBotUsername\(\)\)/)
 assert.match(webhook,/aiVideoBotIdentityReady\(\)/)
 assert.match(webhook,/HH_AI_TELEGRAM_QUEUE_ENABLED==='true'/)
 assert.match(webhook,/VERCEL_ENV==='production'/)
 assert.match(webhook,/receiveTelegramAiUpdate/)
 assert.doesNotMatch(webhook,/setWebhook\(|registerClientTelegramWebhook/)
 assert.doesNotMatch(crm,/receiveTelegramAiUpdate|runTelegramAiQueues/)
 assert.match(crm,/processTelegramDiagnostic/)
})

test('owner private /video and audio, subscriber /ai /voice /tests and client messages keep priority',()=>{
 const ownerVideo=webhook.indexOf('receiveOwnerTelegramVideoWebhook(config,update')
 const ownerAudio=webhook.indexOf('receiveOwnerTelegramAudioWebhook(config,update')
 const ownerAi=webhook.indexOf('const owner=await receiveOwnerAiTelegramWebhook')
 const videoAi=webhook.indexOf('let videoIngress=null,receiveVideoAi=null')
 const subscriber=webhook.indexOf('const subscriber=await receiveSubscriberAiTelegramUpdate')
 const client=webhook.lastIndexOf('receiveClientTelegramWebhook(config,update)')
 assert.ok(ownerVideo>=0&&ownerAudio>ownerVideo&&ownerAi>ownerAudio)
 assert.ok(videoAi>ownerAi&&subscriber>videoAi&&client>subscriber)
 assert.match(webhook,/if\(videoIngress\?\.stop&&receiveVideoAi\)await receiveVideoAi\(config,videoIngress\)/)
 assert.match(webhook,/drainSubscriberAiOutbox/)
 assert.match(webhook,/dispatchPractitionerMessagePush/)
 assert.match(webhook,/dispatchClientTelegramNotification/)
 assert.doesNotMatch(parser,/[/]video(?:\\s|\\$)/)
})

