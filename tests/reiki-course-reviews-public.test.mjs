test('Public review requires separate learner opt-in, owner approval and no PII projection',()=>{
  assert.match(sql,/force row level security/)
  assert.match(sql,/revoke all on app_private\.reiki_course_public_reviews from public,anon,authenticated/)
  assert.match(sql,/account_id=\(select auth\.uid\(\)\)/)
  assert.match(sql,/current_setting\('hh\.practitioner_id',true\)/)
  assert.match(sql,/body_ciphertext text not null/)
  assert.doesNotMatch(sql,/(?:grant|GRANT)\s+(?:all|select)\s+on app_private\.reiki_course_public_reviews\s+to\s+(?:public|anon|authenticated)/)
  assert.match(repo,/body\.consent !== true/)
  assert.match(my,/checked=\{Boolean\(checked\[item\.id\]\)\}/)
  assert.match(my,/action:'submit-review',slideId:item\.id,locale:lang,consent:true/)
  assert.match(my,/action:'withdraw-review',slideId:item\.id/)
  assert.match(pub,/status='approved' and approved_at is not null/)
  assert.match(pub,/order by approved_at desc,id desc limit 16/)
  assert.match(pub,/review: publicText\(row,config\)/)
  assert.match(pub,/await withdrawPublicReview\(db,actor,slideId\)/)
  assert.match(pub,/await db\.query\(\s*'delete from app_private\.reiki_course_public_reviews/)
  assert.match(pub,/seal\(body/)
  assert.match(pub,/openSealed\(row\.body_ciphertext/)
  assert.match(publicEndpoint,/Cache-Control':'no-store/)
  assert.match(listing,/data-reiki-public-reviews/)
  assert.match(landing,/<ReikiPublicReviews locale=\{locale\}/)
  assert.doesNotMatch(listing,/review\.accountId|review\.email|review\.displayName/)
})

test('Owner CRM can approve/reject and student edits revoke previously approved public copy',()=>{
  assert.match(adminEndpoint,/requireAdminRequest/)
  assert.match(adminEndpoint,/createReikiReviewModeration/)
  assert.match(adminEndpoint,/body\.action === 'moderate-review'/)
  assert.match(owner,/data-reiki-review-moderation/)
  assert.match(owner,/moderateReview\(review,'approved'\)/)
  assert.match(owner,/moderateReview\(review,'rejected'\)/)
  assert.match(pub,/row\.status !== 'pending'/)
  assert.match(owner,/unpublish:'Unpublish'/)
  assert.match(pub,/row.status === 'approved' && status === 'rejected'/)
  assert.match(pub,/row\.revision !== expectedRevision/)
  assert.match(repo,/await deleteAllPublicReviews\(db,actor\)/)
  assert.match(repo,/if \(body\.answer !== \(answers\[body\.slideId\] \|\| ''\)\)/)
  assert.match(repo,/await consentToPublicReview\(db,actor,config,answersFrom\(progress,config\)/)
  assert.doesNotMatch(pub,/console\.(?:log|warn|error)|autoPublish|massMail/)
})
