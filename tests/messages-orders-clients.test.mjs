import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')

test('customer orders use existing owner-scoped consultation request records, not copied CRM contacts',()=>{
  const repo=read('lib/app/repository.js')
  const src=repo.slice(repo.indexOf('async myOrderInbox(actor)'),repo.indexOf('async bootstrap(actor'))
  assert.match(src,/transaction\(config, actor, async db/)
  assert.match(src,/accountLock\(db,actor,\{ready:false\}\)/)
  assert.match(src,/where r\.account_id=\$1/)
  assert.match(src,/\[actor\.id\]/)
  assert.match(src,/app\.consultation_requests/)
  assert.match(src,/m\.visibility='participants'/)
  assert.match(src,/m\.author_role='practitioner'/)
  assert.match(src,/await practitionerOwned\(db,actor\)/)
  assert.match(src,/hasMore=rows\.length>100/)
  assert.doesNotMatch(src,/crm_contacts|crm_msg_threads|app_private\.|join app\.client_profiles|insert into/)
})
