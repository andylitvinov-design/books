import test from 'node:test'
import assert from 'node:assert/strict'
import {createMemoryPractitionerYoutubeStore} from '../lib/youtube/practitioner-upload-store.js'
import {practitionerYoutubeSlot,practitionerYoutubeUpload,practitionerYoutubeAccountId} from '../lib/youtube/practitioner-upload-model.mjs'
import {readFileSync} from 'node:fs'

const A='11111111-1111-4111-8111-111111111111',B='22222222-2222-4222-8222-222222222222'
const RU='UCjWq6NHZTQkUr3bC3WbXXcw'
const EN='UCaaaaaaaaaaaaaaaaaaaaaa',OTHER='UC1234567890123456789012'
test('practitioner channels stay within two slots and separate verified users',async()=>{
 const store=createMemoryPractitionerYoutubeStore()
 assert.deepEqual(await store.channels(A),{'1':null,'2':null})
 assert.equal((await store.pair(A,'1',{id:RU,name:'RU'})).id,RU)
 assert.equal((await store.pair(A,'2',{id:EN,name:'EN'})).id,EN)
 assert.deepEqual(await store.channels(B),{'1':null,'2':null})
 await store.pair(B,'1',{id:OTHER,name:'Independent'})
 assert.equal((await store.channels(B))['1'].id,OTHER)
 await assert.rejects(store.pair(A,'1',{id:OTHER,name:'Unrelated'}),/channel_conflict/)
 await assert.rejects(store.pair(B,'2',{id:OTHER,name:'Duplicate'}),/channel_already_connected/)
 await store.disconnect(A,'1')
 assert.equal((await store.channels(A))['1'],null)
 assert.equal((await store.channels(B))['1'].id,OTHER)
})
test('history requires channel identity and Unlisted, is idempotent and tenant-scoped',async()=>{
 const store=createMemoryPractitionerYoutubeStore()
 await store.pair(A,'1',{id:RU,name:'Channel'})
 const input={slot:'1',videoId:'Y4K4piEwwA8',title:'Demo',channelId:RU,privacyStatus:'unlisted'}
 const saved=await store.save(A,input)
 assert.equal(saved.url,'https://www.youtube.com/watch?v=Y4K4piEwwA8')
 assert.equal((await store.save(A,input)).uploadedAt,saved.uploadedAt)
 assert.equal((await store.history(A)).length,1)
 assert.deepEqual(await store.history(B),[])
 await assert.rejects(store.save(A,{...input,slot:'2'}),/invalid_channel/)
 await assert.rejects(store.save(A,{...input,channelId:OTHER}),/wrong_channel/)
 await assert.rejects(store.save(A,{...input,privacyStatus:'private'}),/invalid_visibility/)
 await assert.rejects(store.save(B,input),/invalid_channel/)
 await store.disconnect(A,'1')
 assert.equal((await store.history(A)).length,1)
 await store.pair(A,'1',{id:OTHER,name:'Different'})
 await assert.rejects(store.save(A,{...input,channelId:OTHER}),/history_conflict/)
})
test('channel, slot, account and record inputs fail closed',()=>{
 assert.equal(practitionerYoutubeAccountId(A),A)
 assert.throws(()=>practitionerYoutubeAccountId('foo'),/invalid_account/)
 assert.throws(()=>practitionerYoutubeSlot('3'),/invalid_slot/)
 assert.throws(()=>practitionerYoutubeSlot(1),/invalid_slot/)
 const record={slot:'1',videoId:'Y4K4piEwwA8',title:'Hi',channelId:RU,privacyStatus:'unlisted'}
 assert.throws(()=>practitionerYoutubeUpload({...record,videoId:'javascript:'},RU),/invalid_video_id/)
 assert.throws(()=>practitionerYoutubeUpload({...record,privacyStatus:'public'},RU),/invalid_visibility/)
 assert.throws(()=>practitionerYoutubeUpload({...record,title:''},RU),/invalid_title/)
})
