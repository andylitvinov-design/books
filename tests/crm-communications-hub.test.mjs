import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {crmIntegrationStage} from '../lib/crm/integration-readiness.js'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('CRM channel status never confuses an ENABLED flag with verified configuration',()=>{
  assert.equal(crmIntegrationStage('whatsapp',{enabled:true,configured:false,missingKeys:['HH_CRM_MSG_WHATSAPP_TOKEN']}),'setup')
  assert.equal(crmIntegrationStage('telegram',{enabled:true,configured:false,liveApproved:true,missingKeys:[]}),'setup')
  assert.equal(crmIntegrationStage('sms',{enabled:false,reason:'sms_disabled',missingKeys:[]}),'off')
  assert.equal(crmIntegrationStage('telegram',{configured:true,pilot:true,liveApproved:false,missingKeys:[]}),'pilot')
  assert.equal(crmIntegrationStage('telegram',{configured:true,pilot:true,liveApproved:false,missingKeys:['HH_CRM_MSG_TELEGRAM_TOKEN']}),'setup')
  assert.equal(crmIntegrationStage('whatsapp',{configured:true,liveApproved:false,missingKeys:[]}),'off')
  assert.equal(crmIntegrationStage('instagram',{configured:true,liveApproved:true,missingKeys:[]}),'configured')
  assert.equal(crmIntegrationStage('email',{enabled:true,missingKeys:[]}),'configured')
  assert.equal(crmIntegrationStage('sms',{enabled:true,live:true,missingKeys:[]}),'configured')
  assert.equal(crmIntegrationStage('messenger',undefined),'setup')
})

test('CRM owner-facing integration cards distinguish pilot, readiness and actual delivery',()=>{
  const jsx=read('components/app/crm-integration-diagnostics.jsx')
  assert.match(jsx,/crmIntegrationStage\(kind,item\)/)
  assert.match(jsx,/Только личный пилот/)
  assert.match(jsx,/доставка не проверена/)
  assert.match(jsx,/Separate|разные каналы|разные защищённые/i)
  assert.doesNotMatch(jsx,/item\?\.configured===true\|\|item\?\.enabled===true/)
  assert.doesNotMatch(jsx,/\{t\.error\}/)
  assert.match(jsx,/HH_|missingKeys/)
})

