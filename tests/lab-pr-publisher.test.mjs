import test from 'node:test';
import assert from 'node:assert/strict';
import {generateKeyPairSync,sign} from 'node:crypto';
import {validatePublish} from '../scripts/lab-pr-publisher.mjs';
import {acceptancePayload} from '../scripts/lab-acceptance-signature.mjs';
const a='a'.repeat(40),b='b'.repeat(40);
const {privateKey,publicKey}=generateKeyPairSync('ed25519');
const reviewerPublicKey=publicKey.export({type:'spki',format:'pem'});
const attestation={featureId:'LAB-101',headSha:b,baseSha:a,reviewerId:'agent-independent',evidenceId:'review-123',decision:'LAB_ACCEPTED'};
attestation.signature=sign(null,Buffer.from(acceptancePayload(attestation)),privateKey).toString('base64');
const packet={id:'LAB-101',owner:'agent-dev',status:'RELEASE_CANDIDATE',targetBranch:'codex/public-book-library',headSha:b,baseSha:a,qaPassed:true,testEvidence:true,changedFiles:['app/page.tsx'],acceptance:{accepted:true,headSha:b,reviewEvidenceId:'review-123',attestation}};
const facts={head:b,base:a,prs:[],reviewerPublicKey};
test('signed accepted candidate passes',()=>assert.equal(validatePublish(packet,facts),null));
test('stale base fails',()=>assert.equal(validatePublish(packet,{...facts,base:b}),'stale-sha'));
test('existing PR blocks',()=>assert.equal(validatePublish(packet,{...facts,prs:[{headRefOid:b}]}),'existing-pr'));
test('missing inventory blocks',()=>assert.equal(validatePublish(packet,{...facts,prs:undefined}),'missing-pr-inventory'));
test('no acceptance blocks',()=>assert.equal(validatePublish({...packet,acceptance:null},facts),'acceptance-required'));
test('missing trusted key blocks',()=>assert.equal(validatePublish(packet,{...facts,reviewerPublicKey:undefined}),'independent-signature-required'));
test('tampered signature blocks',()=>assert.equal(validatePublish({...packet,acceptance:{...packet.acceptance,attestation:{...attestation,evidenceId:'changed'}}},facts),'independent-signature-required'));
test('self review blocks',()=>assert.equal(validatePublish({...packet,owner:'agent-independent'},facts),'independent-signature-required'));
