  assert.match(sql,/unique \(account_id,stage\)/)
  assert.match(sql,/payload_ciphertext text not null/)
  assert.match(sql,/enable row level security/)
  assert.match(sql,/force row level security/)
  assert.match(sql,/revoke all on app_private\.reiki_course_leads from public,anon,authenticated/)
  assert.match(sql,/grant select,insert,delete on app_private\.reiki_course_leads to hh_app_backend/)
  assert.match(sql,/grant select on app_private\.reiki_course_leads to hh_app_inbox/)
  assert.match(sql,/current_setting\('hh\.practitioner_id',true\)/)
  assert.match(sql,/app_private\.account_active\(\)/)
  assert.doesNotMatch(sql,/(?:GRANT|grant)\s+(?:all|select|insert)\s+on app_private\.reiki_course_leads\s+to\s+(?:public|anon|authenticated|hh_crm_backend)/i)
