import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
test('briefing carousel uses actual signed-in recommendations, without fictional feed items',()=>{
  const view=read('components/app/messages-daily-briefing.jsx')
  assert.match(view,/buildDailyInsight\(/)
  assert.match(view,/fetchPrivate\('practice',accountId,controller.signal\)/)
  assert.match(view,/credentials:'same-origin',cache:'no-store'/)
  assert.match(view,/visible\.map\(item=>\(\{\.\.\.item,kind:'recommendation'/)
  assert.match(view,/insight\.analytics\.period/)
  assert.match(view,/insight\.services\.published/)
  assert.doesNotMatch(view,/\+24%|\+12%|3 New enquiries|John Doe|Jane Doe/)
  assert.match(view,/timestamp=briefingTime\(lastUpdated,locale\)/)
  assert.match(view,/setLastUpdated\(new Date\(\)\.toISOString\(\)\)/)
  assert.match(view,/v\.refreshed/)
  assert.match(view,/typeof raw|hh-daily-insight-v1/)
  assert.match(view,/personal:next.personal,actions:/)
  assert.doesNotMatch(view,/gtag\(|sendBeacon|localStorage\.setItem\('hh-daily-feed/)
})
test('briefing carousel is swipeable, keyboard accessible, filterable and localized',()=>{
  const view=read('components/app/messages-daily-briefing.jsx')
  const css=read('components/app/messages-daily-briefing.module.css')
  for(const label of ['Лента ваших новостей','Tus novedades','Your personal updates','Брифинг обновлён','Informe actualizado','Briefing refreshed'])
    assert.ok(view.includes(label),label)
  for(const category of ['messages','tasks','news','analytics','personal'])
    assert.ok(view.includes(category),category)
  assert.match(view,/onScroll=\{handleFeedScroll\}/)
  assert.match(view,/onClick=\{\(\)=>jumpToCard\(index\)\}/)
  assert.match(view,/aria-current=\{page===index/)
  assert.match(view,/aria-pressed=\{feedFilter===id\}/)
  assert.match(view,/role="region" tabIndex=\{0\}/)
  assert.match(view,/if\(authStatus!=='authenticated'\|\|!accountId\)/)
  assert.match(css,/scroll-snap-type:x mandatory/)
  assert.match(css,/-webkit-overflow-scrolling:touch/)
  assert.match(css,/@media\(max-width:350px\)/)
  assert.match(css,/@media\(prefers-reduced-motion:reduce\)/)
  for(const existing of ['.stats','.personal','.hero','.settingsLink','.guest'])
    assert.ok(css.includes(existing),existing)
})
