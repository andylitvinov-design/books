 assert.match(store,/where account_id=\$1 and course_run_id=\$2 and session_number=\$3/)
 assert.match(store,/const field=view==='log'\?'log_ciphertext':view==='protocol'\?'ledger_ciphertext':'ledger_ciphertext,meditation_revision,meditation_ciphertext'/)
 assert.match(store,/if\(view==='log'\)\{[\s\S]*?return \{\.\.\.base,log\}/)
 assert.match(store,/if\(view==='protocol'\)return \{\.\.\.base,protocol:\{binding,rows:report.rows\}\}/)
 assert.match(store,/TRUSTED_ANTI_STRESS_ADAPTER_READY=false/)
 assert.match(ui,/view=catalog/)
 assert.match(ui,/activeOwner\.current!==accountId/)
 assert.match(ui,/data\.binding\.protocolId!==day\.protocolId/)
 assert.match(ui,/signal:c\.signal/)
 assert.match(ui,/state\.accountId!==accountId/)
 assert.match(ui,/\['result','protocol','log'\]/)
 assert.match(plan,/<AntiStressArchive key=\{'anti-stress:'\+accountId\+':'\+\(searchParams\?\.get\('antiStressRun'\)\|\|''\)\}/)
 assert.match(plan,/runId=\{searchParams\?\.get\('antiStressRun'\)\|\|null\}/)
