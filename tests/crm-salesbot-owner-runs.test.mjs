import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {SALESBOT_TEMPLATES,simulateSalesbotFlow} from '../lib/crm/salesbot-flow.mjs'
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8')
test('approved preview script can wait and be resumed deterministically without real sending',()=>{
  const flow=SALESBOT_TEMPLATES.find(x=>x.nodes.some(n=>n.type==='choice'))
  const waiting=simulateSalesbotFlow(flow,{locale:'ru',topic:'direction',answers:{}})
  assert.equal(waiting.status,'waiting_for_choice')
  assert.equal(waiting.sent,false)
  assert.equal(waiting.leadCreated,false)
  assert.equal(waiting.paymentReceived,false)
  const resumed=simulateSalesbotFlow(flow,{locale:'ru',topic:'direction',
    answers:{[waiting.waiting.nodeId]:waiting.waiting.options[0].id}})
  assert.equal(resumed.status,'completed')
  assert.equal(resumed.sent,false)
  assert.equal(resumed.leadCreated,false)
})
