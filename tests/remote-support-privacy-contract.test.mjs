import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
test('goal photos use a private bucket and account-scoped proxy, not public Storage URLs',()=>{
  const api=read('app/api/app/remote-support/[id]/photo/route.js')
  const store=read('lib/practitioners/remote-goal-photo.js')
  const migration=read('supabase/migrations/20261023134500_hh_remote_energy_support_booking.sql')
  assert.match(api,/auth\.verified\(\)/)
  assert.match(api,/requireSameOrigin/)
  assert.match(api,/Cache-Control.*private, no-store/)
  assert.match(store,/from app\.consultation_requests r join app\.practitioners p/)
  assert.match(store,/r\.account_id=\$2 or/)
  assert.match(store,/hh-remote-goal-photos/)
  assert.match(store,/\.jpeg\(\{quality:78,mozjpeg:true\}\)/)
  assert.match(migration,/hh-remote-goal-photos',false/)
  assert.doesNotMatch(store,/\/storage\/v1\/object\/public/)
})
test('remote booking remains uncharged and reviews require completed sessions',()=>{
  const booking=read('lib/practitioners/remote-energy-support.js')
  const reviews=read('lib/practitioners/reviews.js')
  const master=read('lib/practitioners/repository.js')
  const member=read('lib/app/repository.js')
  assert.match(booking,/paymentStatus:'not_enabled'/)
  assert.match(reviews,/status='completed'.*remote_booking is not null/)
  assert.match(reviews,/remote\?'hidden':'published'/)
  assert.match(master,/for update'\,\[p.id\]/)
  assert.match(master,/SLOT_UNAVAILABLE/)
  assert.match(member,/accept_time/)
  assert.match(member,/Client agreement restores REQUESTED/)
})
test('one approved Andrey offering only; never forge 10/20 prices or other masters',()=>{
  const sql=read('supabase/migrations/20261023134600_hh_remote_energy_andrey_offer.sql')
  assert.match(sql,/slug='andy-litvinov' and status='approved'/)
  assert.match(sql,/gen_random_uuid\(\)/)
  assert.match(sql,/not exists \(select 1 from app\.service_offerings/)
  assert.match(sql,/'duration',30,'price',50/)
  assert.match(sql,/'duration',60,'price',100/)
  assert.doesNotMatch(sql,/'duration',10,'price'/)
  assert.doesNotMatch(sql,/'duration',20,'price'/)
})
