import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'
import { energyworkSequence, ENERGYWORK_FINISH, energyworkLessonRanges } from '../data/academy/energywork-ai-schema.js'

const read = (path) => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const editorial = read('data/academy/energywork-ai-curriculum.ts')
const learner = read('components/energywork-ai-learner.tsx')
const uploader = read('components/reiki-initiation-photo.tsx')
const privatePhoto = read('lib/academy/reiki-initiation-photo.js')
const api = read('app/api/app/[...path]/route.js')
const repo = read('lib/academy/energywork-course-repository.js')
const leads = read('lib/academy/reiki-course-leads.js')
const admin = read('components/admin-reiki-leads.jsx')
const cabinet = read('components/app/cabinet-free-course-banners.jsx')
const middleware = read('middleware.ts')

test('The penultimate photo step appears exactly once after meditation, before completion', () => {
  const sequence = energyworkSequence()
  assert.deepEqual(sequence.slice(-3), ['intention-04','init-photo-01','end-02'])
  assert.equal(sequence.filter(id => id === 'init-photo-01').length, 1)
  assert.ok(ENERGYWORK_FINISH.includes('init-photo-01'))
  assert.deepEqual(energyworkLessonRanges().map(range => range.count), [7,15,17,15,7])
  assert.match(editorial, /id: "init-photo-01", phase: "complete", kind: "lesson"/)
  assert.match(editorial, /Send your photo for Reiki initiation/)
  assert.match(editorial, /Отправьте своё фото мастеру/)
  assert.match(learner, /slide\.id === "init-photo-01" \? \(/)
  assert.match(learner, /<ReikiInitiationPhoto/)
})

test('Signed-photo upload is authenticated, owner scoped, private and bounded', () => {
  assert.match(api, /joined === 'academy-energywork\/photo'/)
  assert.match(api, /request\.headers\.get\('x-hh-account-id'\)/)
  assert.match(api, /readReikiInitiationPhoto\(config, actor\)/)
  assert.match(api, /saveReikiInitiationPhoto\(config, actor, form\.get\('photo'\)\)/)
  assert.match(api, /consumeRate\(config, \{op:'reiki-photo-upload',actor:actor\.id\}/)
  assert.match(api, /requireSameOrigin\(request, config\)/)
  assert.match(privatePhoto, /createPrivateStorageClient\(config\)/)
  assert.match(privatePhoto, /REIKI_INITIATION_PHOTO_BUCKET = 'hh-remote-goal-photos'/)
  assert.match(privatePhoto, /if \(error \|\| !data \|\| data\.public !== false\)/)
  assert.match(privatePhoto, /return 'reiki-initiation\/' \+ accountId\.toLowerCase\(\) \+ '\/photo\.jpg'/)
  assert.match(privatePhoto, /account_id=\$1 and course_key=\$2/)
  assert.match(privatePhoto, /sequence\.indexOf\(row\.slide_id\) < sequence\.indexOf\(slideId\)/)
  assert.match(privatePhoto, /reikiPrivateJpegValid\(bytes\)/)
  assert.match(privatePhoto, /REIKI_INITIATION_PHOTO_MAX_BYTES = 2_500_000/)
  assert.match(privatePhoto, /reiki-private-jpeg\.js/)
  assert.match(privatePhoto, /createSignedUrl\(reikiInitiationPhotoKey\(actor\.id\), 120\)/)
  assert.doesNotMatch(privatePhoto, /getPublicUrl|public:\s*true|console\.log|storage\.from\('hh-reiki-course-audio'\)/)
})

test('Mobile upload normalizes JPEG, strips EXIF, stays in account and can be revisited', () => {
  assert.match(uploader, /<input type="file" accept="image\/\*"/)
  assert.match(uploader, /context\.drawImage\(image/)
  assert.match(uploader, /canvas\.toBlob/)
  assert.match(uploader, /new File\(\[blob\], "initiation\.jpg"/)
  assert.match(uploader, /fetch\("\/api\/app\/academy-energywork\/photo"/)
  assert.match(uploader, /credentials: "same-origin"/)
  assert.match(uploader, /referrerPolicy="no-referrer"/)
  assert.match(learner, /data-reiki-photo-required/)
  assert.match(learner, /!initiationPhoto\?\.exists/)
  assert.match(cabinet, /data-reiki-cabinet-personal-photo/)
  assert.match(cabinet, /\?slide=init-photo-01/)
  assert.match(middleware, /reikiPhotoOrigin/)
  assert.match(middleware, /pathname !== '\/admin\/reiki-leads'/)
})

test('Application gates require photo and opt-in; CRM gets full encrypted course record and short-lived signed link', () => {
  assert.match(repo, /const photo = await requireReikiInitiationPhoto\(config, actor\)/)
  assert.match(repo, /submitReikiApplication\(db,actor,config,progress,answers,photo\)/)
  assert.match(repo, /body\.confirmed !== true/)
  assert.match(leads, /findLead\(db, actor\.id, 'application'/)
  assert.match(leads, /initiationRequest,\s*answers,\s*photo,/)
  assert.match(leads, /seal\(payload/)
  assert.match(leads, /hasPhoto: row\.stage === 'application'/)
  assert.match(leads, /async photo\(\{ id \}\)/)
  assert.match(leads, /signReikiApplicationPhoto\(config, record\.photo, record\.accountId\)/)
  assert.doesNotMatch(leads, /return Promise\.all\(rows\.map/)
  const endpoint=read('app/admin/reiki-leads/data/route.js')
  assert.match(endpoint, /await inbox\.photo\(\{ id: photoId \}\)/)
  assert.match(endpoint, /requireAdminRequest\(\)/)
  assert.match(privatePhoto, /photo\.key !== reikiInitiationPhotoKey\(accountId\)/)
  assert.match(privatePhoto, /createSignedUrl\(photo\.key, 120\)/)
  assert.match(admin, /data-reiki-crm-initiation-photo/)
  assert.match(admin, /ApplicationPhoto/)
  assert.match(admin, /photoShow/)
  assert.match(admin, /photoReload/)
  assert.match(admin, /CourseAnswers/)
  assert.match(learner, /applicationConsented/)
  assert.match(learner, /checked=\{applicationConsented\}/)
  assert.match(learner, /also share my learning progress|share my photo/i)
  assert.doesNotMatch(leads, /insert into app\.crm_contacts|publish|marketingConsent/)
})
