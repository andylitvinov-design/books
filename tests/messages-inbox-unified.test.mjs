  assert.match(crm,/result\.threads\?\.find\(item=>item\.needsReply\|\|Number\(item\.unreadCount\)>0\)/)
  assert.match(crm,/if\(next\?\.id\)void selectThread\(next\.id\)/)
  assert.match(crm,/if\(!activeRef\.current\)/)
