test('owner CRM inbox boots independently of slow/failed practitioner requests',()=>{
  const route=read('app/api/app/messages/requests/route.js')
  const hub=read('components/app/messages-hub.jsx')
  const requests=read('components/app/messages-client-requests.jsx')
  const css=read('components/app/messages-hub.module.css')
  // A verified signed-in actor may read ONLY the owner permission+account ID.
  const bootstrap=route.indexOf("if(query.get('view')==='owner')")
  const practice=route.indexOf('getMyPractice(actor)')
  assert.ok(bootstrap>route.indexOf('await auth.verified()')&&bootstrap<practice,
    'CRM boot cannot wait for the practitioner query')
  assert.match(route,/ownerMessenger:crmEnabled\(\)&&ownerAuthorized/)
  assert.match(route,/const ownerAuthorized=practitionerEmailAllowed\(actor\)/)
  assert.match(route,/query.getAll\('view'\).length>1/)
  assert.match(route,/headers:PRIVATE_HEADERS/)
  assert.match(hub,/fetch\('\/api\/app\/messages\/requests\?view=owner'/)
  assert.match(hub,/credentials:'same-origin',cache:'no-store',signal:controller.signal/)
  assert.match(hub,/const sameAccount=!data\|\|!ownerInfo\|\|data.accountId===ownerInfo.accountId/)
  assert.match(hub,/const usableData=sameAccount\?data:null/)
  assert.match(hub,/const safeCrmSummary=ownerAccountId\?crmSummary:null/)
  assert.match(hub,/const requestData=usableData\|\|\(ownerAccountId\?/)
  assert.match(hub,/crmState=\{safeCrmSummary\|\|/)
  assert.ok(hub.indexOf('<CrmMessengerPanel')<hub.indexOf('<DirectMessageInbox'))
  assert.match(requests,/data.websiteUnavailable&&<p role="alert"/)
  assert.match(requests,/!data.websiteLoading&&!data.websiteUnavailable/)
  // CRM list and its actionable thread link stay above other request cards.
  assert.ok(requests.indexOf('className={styles.crmLeads}')<requests.indexOf('className={styles.requestLayout}'))
  assert.match(hub,/crmUnreadLeads.length>0&&<button type="button"/)
  assert.match(css,/\.unreadJump\{/)
  const practiceNav=read('components/app/practice-workspace.jsx')
  assert.match(practiceNav,/app\/messages'\+\(isOwner\?'\?tab=requests'/)
  assert.doesNotMatch(route,/HH_CRM_MSG_TELEGRAM_TOKEN|HH_CRM_MSG_TELEGRAM_WEBHOOK_SECRET/)
})
