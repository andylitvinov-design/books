test('legacy Daybook entry leads to the canonical persistent journal in every locale',()=>{
 const source=read('components/app/coaching-daybook.jsx')
 assert.match(source,/href=\{'\/'\+lang\+'\/app\/daybook'\}/)
 for(const label of ['Open my private journal','Открыть личный дневник','Abrir mi diario privado'])assert.ok(source.includes(label))
 assert.match(source,/href=\{'\/'\+lang\+'\/my-coach'\}/)
})
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
test('My Space approved order: heading -> real focus -> one Daybook CTA -> existing cards',()=>{
 const dashboard=read('components/app/profile-space-dashboard.jsx')
 assert.match(dashboard,/<ProfileSpaceFocus locale=\{selected\} root=\{root\} accountId=\{accountId\} \/>/)
 assert.ok(dashboard.indexOf('<ProfileSpaceFocus')>dashboard.indexOf('className={styles.intro}'))
 assert.ok(dashboard.indexOf('<ProfileSpaceFocus')<dashboard.indexOf('className={styles.path}'))
 assert.ok(dashboard.indexOf('className={styles.path}')<dashboard.indexOf('className={styles.cards}'))
 assert.match(dashboard,/Coaching Daybook/)
 assert.match(dashboard,/data-profile-space-path/)
 assert.match(read('components/app/profile-space-dashboard.module.css'), /\.focusChip > span:nth-child\(2\)/)
 assert.match(read('components/app/profile-space-dashboard.module.css'), /\.focusChip > svg:last-child\{flex:none\}/)
 assert.match(dashboard,/href=\{root \+ '\/portrait\?space=path'\}/)
 assert.match(dashboard,/id: 'state'/)
 assert.match(dashboard,/id: 'sessions'/)
})
