import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {
 COURSE_RECORD_LIMITS,selectCourseRecordingMime,normalizeCourseRecordingMime,formatCourseRecordingTime,
} from '../lib/practitioners/course-recorder.js'

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('Safari-friendly MP4/M4A codec selection never disguises WebM as an MP4 file',()=>{
 const supported=new Set(['video/mp4','audio/mp4','video/webm;codecs=vp8,opus'])
 assert.equal(selectCourseRecordingMime('video',t=>supported.has(t)),'video/mp4')
 assert.equal(selectCourseRecordingMime('audio',t=>supported.has(t)),'audio/mp4')
 assert.equal(selectCourseRecordingMime('video',t=>t.includes('webm')),'')
 assert.equal(selectCourseRecordingMime('audio',()=>false),'')
 assert.equal(selectCourseRecordingMime('image',()=>true),'')
 assert.equal(normalizeCourseRecordingMime('video/mp4;codecs="h264,aac"','video'),'video/mp4')
 assert.equal(normalizeCourseRecordingMime('audio/x-m4a;codecs=mp4a.40.2','audio'),'audio/mp4')
 assert.equal(normalizeCourseRecordingMime('video/webm','video'),'')
 assert.equal(normalizeCourseRecordingMime('audio/webm','audio'),'')
 assert.equal(formatCourseRecordingTime(90),'01:30')
 assert.equal(formatCourseRecordingTime(240),'04:00')
 assert.equal(COURSE_RECORD_LIMITS.video.seconds,90)
 assert.equal(COURSE_RECORD_LIMITS.audio.bytes,20000000)
})

