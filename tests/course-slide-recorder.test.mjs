test('Private original video can be manually downloaded for YouTube only by its course owner',()=>{
 const mediaRoute=read('app/api/practitioner-course-media/[id]/route.js')
 const repo=read('lib/practitioners/course-repository.js')
 const builder=read('components/app/practitioner-course-builder.jsx')
 const materials=read('components/app/practice-materials.jsx')
 const practice=read('components/app/practice-workspace.jsx')
 assert.match(mediaRoute,/wantsDownload\?null:await repo\.publicAsset\(id\)/)
 assert.match(mediaRoute,/asset=await repo\.ownAsset\(actor,id\)/)
 assert.match(mediaRoute,/auth\.verified\(\)/)
 assert.match(mediaRoute,/wantsDownload\?await repo\.signedOwnerDownloadUrl\(asset\)/)
 assert.match(repo,/signedOwnerDownloadUrl\(asset\)/)
 assert.match(repo,/createSignedUrl\(asset\.object_key,90,\{download\}\)/)
 assert.match(repo,/\['video\/mp4','video\/quicktime'\]\.includes\(asset\.mime\)/)
 assert.match(builder,/data-course-youtube-handoff/)
 assert.match(builder,/download=1/)
 assert.match(builder,/typeof onOpenYoutube==='function'/)
 assert.match(builder,/https:\/\/studio\.youtube\.com\//)
 assert.match(builder,/do not send private client videos/i)
 assert.match(materials,/onOpenYoutube=\{isOwner\?onOpenYoutube:null\}/)
 assert.match(practice,/onOpenYoutube=\{\(\)=>openOwner\('youtube'\)\}/)
 assert.doesNotMatch(builder,/uploadToYoutube\(|publishYoutubeVideo\(/)
})
