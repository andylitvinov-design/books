import assert from 'node:assert/strict'
import test from 'node:test'
import {readFileSync} from 'node:fs'
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8')
test('Profile Life and Work keep existing public mode switch',()=>{
 const mode=read('components/master-mode-switch.tsx')
 const profile=read('components/app/profile-hub-tabs.jsx')
 const work=read('components/practice-work-profile-intro.jsx')
 assert.match(mode,/data-profile-mode-switch/)
 assert.match(mode,/data-profile-mode="live"/)
 assert.match(mode,/data-profile-mode="work"/)
 assert.match(profile,/ProfileModeSwitch locale=\{selected\} active="live"/)
 assert.match(work,/data-profile-mode-switch/)
 assert.match(work,/data-profile-mode="live"/)
 assert.match(work,/data-profile-mode="work"/)
})
test('guest Life actions open a modal; mode switch bypasses gate',()=>{
 const source=read('components/app/app-workspace.jsx')
 const dialog=read('components/app/profile-guest-auth-dialog.jsx')
 assert.match(source,/onClickCapture=\{interceptGuestProfileAction\}/)
 assert.match(source,/target\.closest\('\[data-profile-mode-switch\]'\)/)
 assert.match(source,/target\.closest\('\[data-profile-language-switch\]'\)/)
 assert.match(source,/target\.closest\('\[data-profile-auth-dialog\]'\)/)
 assert.match(source,/event\.preventDefault\(\)/)
 assert.match(source,/<ProfileGuestAuthDialog/)
 assert.match(source,/onGoogle=\{\(\)=>signin\('google'\)\}/)
 assert.match(source,/onTelegram=\{\(\)=>signin\('telegram'\)\}/)
 assert.match(dialog,/<dialog/)
 assert.match(dialog,/showModal\(\)/)
 assert.match(dialog,/disabled=\{busy\|\|!telegramAvailable\}/)
 assert.match(dialog,/onCancel=\{event/)
})
test('guest Work action buttons and links require sign-in; Telegram is OIDC-gated',()=>{
 const work=read('components/practice-showcase.jsx')
 assert.match(work,/onClickCapture=\{interceptGuestWorkLink\}/)
 assert.match(work,/if \(\['home','masters','community'\]\.includes\(key\)\) \{\s*if \(!signedIn\)/)
 assert.match(work,/target\.closest\('\[data-profile-mode-switch\]'\)/)
 assert.match(work,/target\.closest\('\[data-profile-language-switch\]'\)/)
 assert.match(work,/setPendingAction\('profile'\)/)
 assert.match(work,/onClick=\{\(\) => void confirmTelegramSignIn\(\)\}/)
 assert.match(work,/disabled=\{Boolean\(busy\) \|\| !telegramAvailable\}/)
 assert.match(work,/appFetch\('auth\/start', \{ locale, provider:'telegram', continueTo:'practice-preview' \}\)/)
})
