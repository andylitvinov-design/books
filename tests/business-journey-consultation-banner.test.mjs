test('original business testimony archive is source-backed; active service uses its real video showcase',()=>{
  const route=read('app/[locale]/explore/[theme]/page.tsx')
  const landing=read('components/business-consulting-landing.tsx')
  const proof=read('components/business-testimonials.tsx')
  const testimonials=read('components/personal-testimonials.tsx')
  assert.match(route,/<DirectionOffers locale=\{locale as PublicLocale\}/)
  assert.match(landing,/<ServiceVideoShowcase topic="constellation-case" locale=\{locale\} id="business-constellation-video"/)
  assert.match(landing,/<BusinessWebsiteEnquiry locale=\{locale\}\/>/)
  assert.match(proof,/<SiteVideoPlayer/)
  assert.match(proof,/compact minimal/)
  assert.match(proof,/testimonial-posters/)
  assert.match(proof,/data-business-testimonial-id=\{item\.id\}/)
  const videoIds=['Dk0LBmOivQo','aUJde6A-9p0','ttQxUHopaUM','VABgpmn4ZYA']
  for(const id of videoIds) {
    assert.ok(proof.includes(id),'Missing real business video '+id)
    assert.ok(testimonials.includes(id),'Source archive missing '+id)
    assert.ok(existsSync(new URL('../public/images/holistic-house/testimonial-posters/'+id+'.webp',import.meta.url)),'Archive poster missing '+id)
  }
  assert.doesNotMatch(proof,/storyQuote|fakeReview|\\"I left|\\"I came/)
  assert.match(proof,/individual|individuales|личный опыт/i)
  assert.match(proof,/not independently verified|отдельно не подтверждён|no se verifica/)
})

