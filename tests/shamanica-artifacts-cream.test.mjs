import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
test("cream Shamanic landing keeps six functional categories, places four before featured catalogue",()=>{
 const s=read("components/shamanica-mobile.tsx"),css=read("components/shamanica-mobile.module.css");
 assert.match(s,/data-shamanic-artifact-hero/);
 assert.match(s,/data-shamanic-featured-artifacts/);
 assert.match(s,/href="#shamanic-artifact-list"/);
 assert.match(s,/id="shamanic-artifact-list"/);
 assert.match(s,/Request Session/);
 assert.match(s,/aria-expanded=\{requestOpen\}/);
 assert.match(s,/hidden=\{!requestOpen\}/);
 assert.match(s,/whatsappEnquiryUrl\(/);
 assert.match(s,/telegramEnquiryUrlFromWhatsApp\(whatsapp\)/);
 assert.match(s,/featuredArtifacts\.map/);
 for(const key of ["guidance","rituals","remedies","mysteries","energy","academy"]) assert.ok(s.includes('id:"'+key+'"'));
 for(const key of ["personal","fu","mandala"])assert.ok(s.includes('id:"'+key+'"'));
 assert.match(css,/SHAMANIC_ARTIFACT_CREAM_20261127/);
 assert.match(css,/grid-template-columns:33% minmax\(0,1fr\)/);
 assert.match(s,/shelfButtons\.slice\(0,4\)/);
 assert.match(s,/shelfButtons\.slice\(4\)/);
 assert.ok(s.indexOf("shelfButtons.slice(0,4)")<s.indexOf('id="shamanic-artifact-list"'));
 assert.ok(s.indexOf('id="shamanic-artifact-list"')<s.indexOf("shelfButtons.slice(4)"));
 assert.match(css,/shamanic-owner-artifact-hero-20261127\.webp/);
 assert.match(css,/shamanic-owner-category-crops-20261127\.webp/);
 assert.match(css,/aspect-ratio:1;min-height:0/);
 assert.match(css,/background-size:cover/);
 assert.match(css,/\.sessionContact\[hidden\]\{display:none\}/);
 assert.match(s,/ShamanicaBusinessContent locale=\{locale\}/);
});
