import test from 'node:test'
import assert from 'node:assert/strict'
import {newClarityClock,transitionClarityClock,clarityClockView,CLARITY_CLOCK_LIMIT_MS} from '../lib/coaching/clarity-logical-clock.mjs'
const id=n=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0')
const start=(s,op,persona='mira')=>({action:'start',revision:s.revision,operationId:id(op),personaId:persona,confirmed:true})
const pulse=(s,op,action='pulse')=>({action,revision:s.revision,operationId:id(op),segmentId:s.segmentId})
test('greeting is free, explicit start and verified server-time pulses accumulate across coaches',()=>{
 let s=newClarityClock(1,id(1))
 assert.equal(clarityClockView(s).remainingMs,1200000)
 assert.throws(()=>transitionClarityClock(s,{...start(s,2),confirmed:false},100000,id(3)))
 s=transitionClarityClock(s,start(s,2),100000,id(3))
 const first=pulse(s,4)
 s=transitionClarityClock(s,first,110000)
 assert.equal(s.activeMs,10000)
 assert.equal(transitionClarityClock(s,first,115000).activeMs,10000)
 assert.throws(()=>transitionClarityClock(s,{...first,action:'pause'},115000))
 const old=pulse(s,5)
 s=transitionClarityClock(s,pulse(s,6,'pause'),115000)
 assert.equal(s.activeMs,10000);assert.equal(s.phase,'paused')
 s=transitionClarityClock(s,start(s,7,'caesar'),900000,id(8))
 assert.equal(s.protocolId,id(1));assert.equal(s.activeMs,10000);assert.equal(s.personaId,'caesar')
 assert.throws(()=>transitionClarityClock(s,old,910000))
 s=transitionClarityClock(s,pulse(s,9),910000)
 assert.equal(s.activeMs,20000)
})
test('lost connection is never completion, stale lease cannot advance time',()=>{
 let s=newClarityClock(1,id(1))
 s=transitionClarityClock(s,start(s,2),1000,id(3))
 assert.throws(()=>transitionClarityClock(s,start(s,4,'caesar'),2000,id(5)))
 s=transitionClarityClock(s,pulse(s,6),50000)
 assert.equal(s.phase,'paused');assert.equal(s.activeMs,0)
 s=transitionClarityClock(s,start(s,7,'caesar'),100000,id(8))
 s=transitionClarityClock(s,pulse(s,9),110000)
 assert.equal(s.activeMs,10000)
 s=transitionClarityClock(s,start(s,10,'mira'),200000,id(11))
 assert.equal(s.activeMs,10000);assert.equal(s.protocolId,id(1))
})
test('normal 20-minute cap only on a pulse, review requires a separate explicit decision',()=>{
 let s=newClarityClock(1,id(1))
 s=transitionClarityClock(s,start(s,2),1000,id(3))
 for(let i=1;i<=120;i++)s=transitionClarityClock(s,pulse(s,10+i),1000+i*10000)
 assert.equal(s.activeMs,CLARITY_CLOCK_LIMIT_MS);assert.equal(s.phase,'review');assert.equal(s.segmentId,null)
 assert.throws(()=>transitionClarityClock(s,start(s,300),1300000,id(301)))
 assert.throws(()=>transitionClarityClock(s,{action:'review',revision:s.revision,operationId:id(302),confirmed:false},1300000))
 const end={action:'review',revision:s.revision,operationId:id(303),confirmed:true}
 s=transitionClarityClock(s,end,1300000)
 assert.equal(s.phase,'closed')
 assert.equal(transitionClarityClock(s,end,1400000),s)
 assert.equal(clarityClockView(s).remainingMs,0)
})
test('pause at boundary and delayed heartbeat never create a timed close',()=>{
 let s=newClarityClock(1,id(1));s=transitionClarityClock(s,start(s,2),1000,id(3))
 for(let i=1;i<=119;i++)s=transitionClarityClock(s,pulse(s,10+i),1000+i*10000)
 assert.equal(s.activeMs,1190000)
 s=transitionClarityClock(s,pulse(s,200,'pause'),1201000)
 assert.equal(s.phase,'paused');assert.equal(s.activeMs,1190000)
 s=transitionClarityClock(s,start(s,201),1300000,id(202))
 s=transitionClarityClock(s,pulse(s,203),1340000)
 assert.equal(s.phase,'paused');assert.equal(s.activeMs,1190000)
})
