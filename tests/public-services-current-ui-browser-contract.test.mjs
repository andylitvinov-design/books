import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'

const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')

test('public acceptance targets currently mounted first-party UI, never retired screens',()=>{
 const support=read('scripts/verify-holistic-support-recommendations-mobile.mjs')
 const home=read('scripts/verify-home-consultation-first-screen.mjs')
 const master=read('scripts/verify-holistic-master-browser.mjs')
 const business=read('scripts/verify-business-quiz-mobile.mjs')
 const topics=read('scripts/verify-holistic-topics-browser.mjs')
 assert.match(support,/one recommendation action/)
 assert.match(support,/data-support-active-focus/)
 assert.match(support,/serviceWorkers: "block"/)
 assert.match(home,/data-home-module-action="review"/)
 assert.match(home,/data-home-conversation-guide/)
 assert.match(master,/data-holistic-choose="dao"/)
 assert.match(master,/data-holistic-dao-screen/)
 assert.match(master,/data-holistic-meditation-gallery/)
 assert.match(business,/data-direction-offers/)
 assert.doesNotMatch(business,/data-business-consultation-finder/)
 assert.match(business,/data-goal-support-offers/)
 assert.match(business,/forbiddenRequests/)
 assert.match(topics,/serviceWorkers: "block"/)
 assert.match(topics,/data-support-budget/)
 assert.match(topics,/synthetic-consultation-directory/)
})
test('checkout and Reiki acceptance preserve consent, data isolation and genuine hydration',()=>{
 const talisman=read('scripts/verify-talisman-google-checkout-browser.mjs')
 const reiki=read('scripts/verify-reiki-mobile-order-browser.mjs')
 const storefront=read('scripts/verify-storefront-shop-browser.mjs')
 assert.match(talisman,/ratingsRequest/)
 assert.match(talisman,/data-talisman-reply-consent/)
 assert.match(talisman,/captured\.enquiries\.length,1/)
 assert.match(reiki,/__reactProps\$/)
 assert.match(reiki,/data-support-master-request/)
 assert.match(reiki,/contactConsent,true/)
 assert.match(storefront,/__reactProps\$/)
 assert.match(storefront,/input\[type="checkbox"\]\[required\]/)
 assert.match(storefront,/contactConsent, true/)
 assert.match(storefront,/syntheticEnquiries\.length, 1/)
 assert.match(storefront,/serviceWorkers: 'block'/)
 assert.doesNotMatch(storefront,/\.check\(\{force:true\}\)|dispatchEvent\(/)
})
