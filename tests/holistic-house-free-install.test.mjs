test('a captured browser offer is consumed once even before the choice settles',async()=>{
  const source=read('lib/pwa/install-prompt.js')
  const {capturePwaInstallPrompt,onPwaInstallPrompt,pwaInstalled,requestPwaInstallation}=
    await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))
  const states=[]
  let calls=0,prevented=false,resolveChoice
  const userChoice=new Promise(resolve=>{resolveChoice=resolve})
  capturePwaInstallPrompt({preventDefault(){prevented=true},prompt(){calls++},userChoice})
  const unsubscribe=onPwaInstallPrompt(offer=>states.push(Boolean(offer)))
  assert.deepEqual(states,[true],'offer is retained for a subscriber that mounts later')
  const first=requestPwaInstallation()
  assert.deepEqual(await requestPwaInstallation(),{available:false,accepted:false})
  assert.equal(calls,1)
  assert.equal(prevented,true)
  resolveChoice({outcome:'dismissed'})
  assert.deepEqual(await first,{available:true,accepted:false})
  capturePwaInstallPrompt({prompt(){calls++},userChoice:Promise.resolve({outcome:'accepted'})})
  assert.deepEqual(await requestPwaInstallation(),{available:true,accepted:true})
  pwaInstalled()
  assert.deepEqual(states,[true,false,true,false,false])
  unsubscribe()
})
