import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
test('Messenger integrates AI, Orders, Clients on one screen and preserves privacy',()=>{
 const hub=read('components/app/messages-orders-clients.jsx')
 const agent=read('components/holistic-agent-chat.tsx')
 const workspace=read('components/app/messenger-ai-workspace.jsx')
 assert.match(hub,/section==='ai'/)
 assert.match(hub,/id="hh-ai-panel"/)
 assert.match(hub,/id="hh-orders-panel"/)
 assert.match(hub,/id="hh-clients-panel"/)
 assert.match(hub,/onClick=\{\(\)=>chooseSection\('ai'\)\}/)
 assert.match(workspace,/HolisticAgentChat locale=\{locale\} compact quickPrompt=\{quickPrompt\}/)
 assert.match(agent,/fetch\("\/api\/holistic-agent\/turn"/)
 assert.match(agent,/ownedInferenceConsent:mode==="owned"&&agree/)
 assert.match(agent,/if\(!quickPrompt\)return/)
 assert.match(agent,/composerRef.current\?\.focus/)
})
test('five narrow quick actions are explicit user choices, not fake renders or external sends',()=>{
 const workspace=read('components/app/messenger-ai-workspace.jsx')
 const css=read('components/app/messenger-ai-workspace.module.css')
 for(const id of ['video','meditation','practice','course','ritual'])
  assert.match(workspace,new RegExp("id:'"+id+"'"))
 assert.match(workspace,/data-chat-menu-rail/)
 assert.match(workspace,/aria-pressed=\{selected===task.id\}/)
 assert.match(workspace,/setQuickPrompt\(prev=>/)
 assert.match(css,/grid-template-columns:64px minmax\(0,1fr\)/)
 assert.match(css,/grid-template-columns:56px minmax\(0,1fr\)/)
 assert.doesNotMatch(workspace,/fetch\(/)
 assert.doesNotMatch(workspace,/data-hh-unified-dock/)
})
test('global AI/Chat goes to Messenger; video director stays an explicit tool',()=>{
 const dock=read('lib/unified-mobile-dock.mjs')
 const workspace=read('components/app/messenger-ai-workspace.jsx')
 assert.match(dock,/case "ai": return prefix\+"\/app\/messages\?section=ai"/)
 assert.match(workspace,/holistic-support\/mandala#video-director-chat/)
 assert.match(read('app/unified-mobile-dock.css'),/data-hh-unified-dock/)
})
