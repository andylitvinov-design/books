test('CRM follow-up kinds and Toronto dates are strict with no past or implausible dates',()=>{
  assert.deepEqual(PRACTITIONER_TASK_KINDS,['reply','call','booking','check_in','general'])
  assert.ok(taskKindAllowed('check_in'))
  assert.equal(taskKindAllowed('prescribe'),false)
  assert.equal(torontoToday(new Date('2026-10-20T13:00:00Z')),'2026-10-20')
  assert.equal(torontoToday(new Date('2026-11-03T02:00:00Z')),'2026-11-02')
  for(const day of ['2026-10-20','2026-10-21','2027-10-20']){
    assert.equal(validTaskDay(day,'2026-10-20'),true,day)
  }
  for(const day of ['2026-10-19','2026-02-30','2026-13-01','',null,
    'tomorrow','2029-01-01','2026-10-20T00:00:00Z']){
    assert.equal(validTaskDay(day,'2026-10-20'),false,String(day))
  }
})
